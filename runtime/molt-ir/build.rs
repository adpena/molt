//! Generates the closed backend environment key set from
//! `src/molt/backend_environment.json`, the one membership authority that the
//! CLI also reads. A key or group added there becomes an enum variant here, so
//! every exhaustive consumer must handle it before the compiler builds.

#![expect(
    clippy::disallowed_methods,
    reason = "Cargo hands a build script its directories through the environment"
)]

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

const SCHEMA: u64 = 1;

fn main() {
    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"),
    );
    let catalog_path = manifest_dir.join("../../src/molt/backend_environment.json");
    println!("cargo:rerun-if-changed={}", catalog_path.display());
    let text = std::fs::read_to_string(&catalog_path)
        .unwrap_or_else(|err| panic!("read {}: {err}", catalog_path.display()));
    let catalog: serde_json::Map<String, serde_json::Value> = serde_json::from_str(&text)
        .unwrap_or_else(|err| panic!("parse {}: {err}", catalog_path.display()));

    let mut groups: Vec<(String, Vec<String>)> = Vec::new();
    let mut seen = BTreeSet::new();
    for (group, value) in &catalog {
        if group == "schema" {
            assert_eq!(
                value.as_u64(),
                Some(SCHEMA),
                "unsupported backend environment catalog schema"
            );
            continue;
        }
        assert!(
            !group.is_empty()
                && group
                    .bytes()
                    .all(|byte| byte.is_ascii_lowercase() || byte == b'_'),
            "malformed backend environment group {group:?}"
        );
        let names = value
            .as_array()
            .unwrap_or_else(|| panic!("backend environment group {group} must be an array"))
            .iter()
            .map(|name| {
                let name = name.as_str().unwrap_or_else(|| {
                    panic!("backend environment group {group} holds a non-string")
                });
                assert!(
                    !name.is_empty()
                        && name.bytes().all(|byte| byte.is_ascii_uppercase()
                            || byte.is_ascii_digit()
                            || byte == b'_'),
                    "malformed backend environment name {name:?}"
                );
                assert!(
                    seen.insert(name.to_string()),
                    "duplicate backend environment entry {name}"
                );
                name.to_string()
            })
            .collect();
        groups.push((group.clone(), names));
    }

    let group_variant = |group: &str| -> String {
        group
            .split('_')
            .map(|part| {
                let mut chars = part.chars();
                chars
                    .next()
                    .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                    .unwrap_or_default()
            })
            .collect()
    };

    let mut out = String::new();
    out.push_str(
        "// @generated by runtime/molt-ir/build.rs from src/molt/backend_environment.json.\n\n",
    );
    out.push_str("/// A backend environment group.\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]\n");
    out.push_str("pub enum BackendEnvGroup {\n");
    for (group, _) in &groups {
        writeln!(out, "    {},", group_variant(group)).unwrap();
    }
    out.push_str("}\n\n");
    out.push_str("/// One backend environment variable. Variants keep the variable's spelling.\n");
    out.push_str("#[allow(non_camel_case_types)]\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]\n");
    out.push_str("pub enum BackendEnv {\n");
    for (_, names) in &groups {
        for name in names {
            writeln!(out, "    {name},").unwrap();
        }
    }
    out.push_str("}\n\nimpl BackendEnv {\n");
    out.push_str("    /// Every variable, in catalog order.\n");
    out.push_str("    pub const ALL: &'static [BackendEnv] = &[\n");
    for (_, names) in &groups {
        for name in names {
            writeln!(out, "        BackendEnv::{name},").unwrap();
        }
    }
    out.push_str("    ];\n\n");
    out.push_str("    /// The variable's name in the process environment.\n");
    out.push_str("    pub const fn name(self) -> &'static str {\n        match self {\n");
    for (_, names) in &groups {
        for name in names {
            writeln!(out, "            BackendEnv::{name} => \"{name}\",").unwrap();
        }
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The group that owns the variable.\n");
    out.push_str("    pub const fn group(self) -> BackendEnvGroup {\n        match self {\n");
    for (group, names) in &groups {
        for name in names {
            writeln!(
                out,
                "            BackendEnv::{name} => BackendEnvGroup::{},",
                group_variant(group)
            )
            .unwrap();
        }
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The variable with this exact name, if the catalog declares one.\n");
    out.push_str(
        "    pub fn from_name(name: &str) -> Option<BackendEnv> {\n        match name {\n",
    );
    for (_, names) in &groups {
        for name in names {
            writeln!(out, "            \"{name}\" => Some(BackendEnv::{name}),").unwrap();
        }
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n");

    let out_path = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"))
        .join("backend_environment_keys.rs");
    std::fs::write(&out_path, out)
        .unwrap_or_else(|err| panic!("write {}: {err}", out_path.display()));
}
