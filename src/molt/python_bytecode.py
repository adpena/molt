"""CPython bytecode format and exact source derivation, without cache policy.

The 16-byte header follows PEP 552 and CPython's py_compile producer. These
operations perform no filesystem discovery or writes; payload verification has
one compile and marshal serialization, as required for borrowed cache custody.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum, auto
import importlib.util
import marshal
import struct
from typing import Literal


PythonOptimization = Literal[0, 1, 2]


class PythonBytecodeFailure(Enum):
    HEADER = auto()
    FLAGS = auto()
    SOURCE_HASH = auto()
    SOURCE_METADATA = auto()
    OPTIMIZATION = auto()
    PAYLOAD = auto()


class PythonBytecodeError(ValueError):
    def __init__(self, failure: PythonBytecodeFailure, message: str) -> None:
        super().__init__(message)
        self.failure = failure


@dataclass(frozen=True)
class TimestampBytecodeHeader:
    timestamp: int
    source_size: int


@dataclass(frozen=True)
class HashBytecodeHeader:
    source_hash: bytes
    mode: Literal["checked", "unchecked"]


PythonBytecodeHeader = TimestampBytecodeHeader | HashBytecodeHeader


class BytecodeSourceDisposition(Enum):
    MATCHES = auto()
    MISSING_TIMESTAMP_METADATA = auto()


def validate_python_optimization(value: int) -> PythonOptimization:
    if type(value) is not int or value not in (0, 1, 2):
        raise PythonBytecodeError(
            PythonBytecodeFailure.OPTIMIZATION,
            "generated bytecode optimization level is unsupported",
        )
    return value


def compile_checked_hash_bytecode(
    source: bytes, filename: str, *, optimize: PythonOptimization
) -> bytes:
    """Produce CPython checked-hash bytecode for exactly these compile inputs."""
    optimization = validate_python_optimization(optimize)
    code = compile(source, filename, "exec", dont_inherit=True, optimize=optimization)
    return (
        importlib.util.MAGIC_NUMBER
        + struct.pack("<I", 0b11)
        + importlib.util.source_hash(source)
        + marshal.dumps(code)
    )


def parse_bytecode_header(bytecode: bytes) -> PythonBytecodeHeader:
    if len(bytecode) < 16 or bytecode[:4] != importlib.util.MAGIC_NUMBER:
        raise PythonBytecodeError(
            PythonBytecodeFailure.HEADER,
            "generated bytecode has an invalid CPython header",
        )
    flags = struct.unpack_from("<I", bytecode, 4)[0]
    if flags & ~0b11:
        raise PythonBytecodeError(
            PythonBytecodeFailure.FLAGS,
            "generated bytecode uses unsupported header flags",
        )
    if flags & 0b1:
        return HashBytecodeHeader(
            bytecode[8:16], "checked" if flags & 0b10 else "unchecked"
        )
    timestamp, source_size = struct.unpack_from("<II", bytecode, 8)
    return TimestampBytecodeHeader(timestamp, source_size)


def validate_bytecode_source(
    header: PythonBytecodeHeader,
    source: bytes,
    *,
    source_mtime: float | None,
) -> BytecodeSourceDisposition:
    """Validate header binding; absent timestamp metadata remains explicit."""
    if isinstance(header, HashBytecodeHeader):
        if header.source_hash != importlib.util.source_hash(source):
            raise PythonBytecodeError(
                PythonBytecodeFailure.SOURCE_HASH,
                "generated bytecode source hash is invalid",
            )
    else:
        if source_mtime is None:
            return BytecodeSourceDisposition.MISSING_TIMESTAMP_METADATA
        if header.timestamp != (int(source_mtime) & 0xFFFFFFFF) or (
            header.source_size != (len(source) & 0xFFFFFFFF)
        ):
            raise PythonBytecodeError(
                PythonBytecodeFailure.SOURCE_METADATA,
                "generated bytecode source metadata is invalid",
            )
    return BytecodeSourceDisposition.MATCHES


def validate_bytecode_payload(
    bytecode: bytes,
    source: bytes,
    filename: str,
    *,
    optimize: PythonOptimization,
) -> None:
    """Validate the payload after parse_bytecode_header/validate_bytecode_source.

    A valid source hash alone cannot attest code, filename or optimization.
    Keeping this phase separate lets custody reject unadmitted rewrite producers
    before compiling, and preserve missing timestamp metadata as unowned input.
    """
    optimization = validate_python_optimization(optimize)
    expected = compile(
        source, filename, "exec", dont_inherit=True, optimize=optimization
    )
    if bytecode[16:] != marshal.dumps(expected):
        raise PythonBytecodeError(
            PythonBytecodeFailure.PAYLOAD,
            "generated bytecode does not match its owned source",
        )


def validate_bytecode_derivation(
    bytecode: bytes,
    source: bytes,
    filename: str,
    *,
    optimize: PythonOptimization,
    source_mtime: float | None,
) -> BytecodeSourceDisposition:
    """Receive complete bytecode and attest header plus exact compile inputs."""
    header = parse_bytecode_header(bytecode)
    disposition = validate_bytecode_source(header, source, source_mtime=source_mtime)
    if disposition is BytecodeSourceDisposition.MISSING_TIMESTAMP_METADATA:
        return disposition
    validate_bytecode_payload(bytecode, source, filename, optimize=optimize)
    return disposition
