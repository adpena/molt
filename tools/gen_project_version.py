#!/usr/bin/env python3
"""Project the package version into code that standalone guests can import."""

from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from tools.generator_io import generator_main  # noqa: E402


def generated_outputs() -> dict[Path, str]:
    with (_REPO_ROOT / "pyproject.toml").open("rb") as handle:
        version = tomllib.load(handle)["project"]["version"]
    if not isinstance(version, str) or not version:
        raise ValueError("project.version must be a nonempty string")
    return {
        _REPO_ROOT / "src/molt/_version.py": (
            "# @generated by tools/gen_project_version.py from pyproject.toml.\n"
            "# Do not edit; run python tools/gen_project_version.py --write.\n"
            "\n\n"
            "def version() -> str:\n"
            '    """The version of this source or installed package, without host IO."""\n'
            f"    return {json.dumps(version)}\n"
        )
    }


def main(argv: list[str] | None = None) -> int:
    return generator_main(generated_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
