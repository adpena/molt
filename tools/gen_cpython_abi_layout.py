#!/usr/bin/env python3
"""Generate the CPython-ABI struct-layout parity assertions from ONE authority.

Single-authority contract
--------------------------
The standalone ``libmolt_cpython_abi.{so,dll,dylib}`` link tier exposes CPython
3.12 objects in the *traditional* ``ob_refcnt`` / ``ob_type`` representation. That
representation is defined ONCE, in Rust ``#[repr(C)]`` form, at

    runtime/molt-cpython-abi/src/abi_types.rs      (the AUTHORITY)

The companion C header

    runtime/molt-cpython-abi/include/Python.h       (the CONSUMER)

hand-declares the *same* structs so C extensions can be compiled against them.
Because the cdylib operates on pointers to the Rust structs, the C struct layout
MUST be byte-identical to the Rust struct layout, or every extension linking the
standalone dylib is memory-unsafe. Historically the two were hand-synced (the D1
"duplicate_authority" poison in tools/fail_closed_registry.toml): a silent drift
in field order/width in either file is undetected memory corruption.

This generator removes the hand-sync. It parses the Rust ``#[repr(C)]`` authority
and emits a *generated* C header,

    runtime/molt-cpython-abi/include/_molt_abi_layout.generated.h

containing, for every struct that also appears in the C umbrella header, a block
of ``_Static_assert`` checks pinning ``sizeof`` and every field ``offsetof`` to
the value the Rust authority dictates. The C header ``#include``s this file, so a
drifting C struct fails to *compile* — the drift can no longer ship. The Rust
authority is the only place a layout is *authored*; the C side is *checked*
against it, not independently maintained.

This is the ``--check``-gated generated-fact pattern used across Molt (op_kinds,
wasm_abi): source-of-truth in one file, generated artifact checked in, a gate
that fails closed when they diverge.

Layout model
------------
The parity we assert is *layout category* per field, in declaration order, which
on the LP64 (Linux/macOS x86-64 & aarch64) and LLP64 (Windows) targets both
sides claim is sufficient to pin byte offsets:

    ptr8   any pointer / fn-pointer / Option<extern fn>  -> 8 bytes, 8-align
    word8  isize/usize/Py_ssize_t/Py_hash_t              -> 8 bytes, 8-align
    i32    c_int/c_uint/i32/u32                           -> 4 bytes, 4-align
    byte1  c_char/u8/i8/bool                              -> 1 byte,  1-align
    f64    c_double/f64                                   -> 8 bytes, 8-align
    embed:<Struct>   an embedded struct value (recursed)
    arr:<n>x<cat>    a fixed C array of <n> elements of <cat>

Because these categories fix each field's size AND alignment, and the C header
and the Rust authority are both ``repr(C)`` with identical field order, the C
compiler's ``_Static_assert`` on ``sizeof``/``offsetof`` is the real proof; the
category table is only used to decide *which* structs and fields to assert and to
detect field-count/kind drift at generation time (a second, cheaper guard).

Usage
-----
    python tools/gen_cpython_abi_layout.py --check    # gate: fail on drift
    python tools/gen_cpython_abi_layout.py --write    # regenerate the artifact
    python tools/gen_cpython_abi_layout.py --print-authority   # debug dump
"""

