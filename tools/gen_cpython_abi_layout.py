I32 = "i32"
BYTE = "byte1"
F64 = "f64"


@dataclass(frozen=True)
class Field:
    name: str
    category: str  # one of the scalars above, or "embed:<Name>", or "arr:<n>x<cat>"


@dataclass(frozen=True)
class Struct:
    name: str
    fields: tuple[Field, ...]


class LayoutError(RuntimeError):
    pass


# ─────────────────────────────────────────────────────────────────────────────
# Rust #[repr(C)] authority parser (brace-aware, multi-line-field safe)
# ─────────────────────────────────────────────────────────────────────────────
def _rust_field_category(ty: str) -> str:
    ty = ty.strip().rstrip(",").strip()
    # Pointers and Option<fn> / fn pointers are all 8-byte pointer-width.
    if (
        ty.startswith("*mut")
        or ty.startswith("*const")
        or ty.startswith("Option<")
        or "extern \"C\" fn" in ty
        or ty.endswith("Func")
        or ty in {"getter", "setter"}
    ):
        return PTR
    if ty in {"Py_ssize_t", "Py_hash_t", "Py_uhash_t", "isize", "usize", "c_ulong"}:
        # NOTE: c_ulong is 8 on LP64 but 4 on LLP64 (Windows). tp_flags/tp_version_tag
        # use it; CPython itself declares those as `unsigned long`, so the C header and
        # Rust agree on the same platform-variadic width. We categorise it as WORD for
        # LP64; the compile-time _Static_assert (emitted per struct) is the real cross
        # platform proof — see the c_ulong handling note in emit.
        return WORD
    if ty in {"c_int", "c_uint", "i32", "u32"}:
        return I32
    if ty in {"c_char", "u8", "i8", "bool"}:
        return BYTE
    if ty in {"c_double", "f64"}:
        return F64
    # Fixed array: [u8; 10], [c_char; 1], [u32; 1]
    m = re.match(r"\[\s*(.+?)\s*;\s*(\d+)\s*\]", ty)
    if m:
        inner = _rust_field_category(m.group(1))
        return f"arr:{m.group(2)}x{inner}"
    # Bare identifier -> embedded struct value (e.g. PyObject, PyVarObject, Py_complex).
    if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", ty):
        return f"embed:{ty}"
    raise LayoutError(f"unclassifiable Rust field type: {ty!r}")


def parse_rust_authority(text: str) -> dict[str, Struct]:
    out: dict[str, Struct] = {}
    lines = text.splitlines()
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        if line.strip() == "#[repr(C)]":
            # Skip any intervening attributes / doc lines to the struct header.
            j = i + 1
            while j < n and not re.match(r"\s*pub struct \w+", lines[j]):
                # Stop if we hit something that isn't an attribute/comment (e.g. a
                # repr(u8) enum, which we do not treat as a layout struct).
                s = lines[j].strip()
                if s and not (
                    s.startswith("#[") or s.startswith("//") or s.startswith("pub struct")
                ):
                    break
                j += 1
            if j < n:
                m = re.match(r"\s*pub struct (\w+)\s*\{", lines[j])
                if m:
                    name = m.group(1)
                    fields, end = _parse_rust_struct_body(lines, j)
                    out[name] = Struct(name, tuple(fields))
                    i = end + 1
                    continue
        i += 1
    return out


def _parse_rust_struct_body(lines: list[str], header_idx: int) -> tuple[list[Field], int]:
    """Parse a ``pub struct Name {`` body starting at ``header_idx`` (the line with
    the opening brace). Returns (fields, index_of_closing_brace_line)."""
    depth = 0
    fields: list[Field] = []
    buf = ""
    i = header_idx
    started = False
    while i < len(lines):
        # Strip a whole-line comment / doc-comment before scanning, so a `///`
        # line inside the body never contaminates the accumulated field buffer.
        raw = lines[i]
        stripped = raw.lstrip()
        line = "" if stripped.startswith("//") else _strip_trailing_line_comment(raw)
        for ch in line:
            if ch == "{":
                depth += 1
                started = True
                continue
            if ch == "}":
                depth -= 1
                if depth == 0:
                    _flush_rust_field(buf, fields)
                    return fields, i
                continue
            if depth == 1:
                if ch == ",":
                    _flush_rust_field(buf, fields)
                    buf = ""
                else:
                    buf += ch
        if started and depth == 1:
            buf += " "  # newline within a multi-line field type
        i += 1
    raise LayoutError(f"unterminated struct body at line {header_idx}")


def _strip_trailing_line_comment(line: str) -> str:
    """Remove a `// ...` trailing comment but keep code before it. Naive but the
    abi_types.rs authority contains no `//` inside string/char literals in struct
    bodies, so a plain split is safe here."""
    idx = line.find("//")
    return line if idx < 0 else line[:idx]


def _flush_rust_field(buf: str, fields: list[Field]) -> None:
    frag = buf.strip()
    if not frag:
        return
    # Strip inline comments and attributes.
    frag = re.sub(r"//.*$", "", frag).strip()
    if not frag or frag.startswith("#["):
        return
    m = re.match(r"pub\s+(\w+)\s*:\s*(.+)$", frag)
    if not m:
        return
    name, ty = m.group(1), m.group(2).strip()
    fields.append(Field(name, _rust_field_category(ty)))


