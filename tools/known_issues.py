#!/usr/bin/env python3
"""Generate the v0.1 known-issues list from the findings ledger. Never edit it by hand.

The list has the Tier 1 cells (``molt.release_matrix.TIER1_CELLS``) with the
verified-subset coordinate that proves each, then every open ledger row grouped
by its v0.1 class (``finding_status.V01Class``): the rows that hold v0.1 (class
``v0_1_blocking`` or no class yet), the Tier 2 rows and the rows after v0.1.

Rendering is pure: ``render`` takes the ledger text. The CLI reads the checkout's
ledger, or with ``--source-sha`` the ledger blob at that commit, as the release
exit gate does. The release-line slice of HF-620 appends this list to a 0.x
release's notes (docs/design/v0_1_support_matrix.md, section 11).

Usage (`uv run --python 3.12 python -B` as the interpreter):
    tools/known_issues.py [--source-sha SHA] [--output FILE]
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from molt.release_matrix import TIER1_CELLS, Tier1Cell  # noqa: E402
from molt.verified_subset import VerifiedSubsetCoordinate, tier1_coordinates  # noqa: E402
from tools import finding_status  # noqa: E402

ROOT = _REPO_ROOT
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z`(])")
_SUMMARY_LIMIT = 240


def summary(finding_cell: str) -> str:
    """The first sentence of a finding cell, bounded for a one-line entry."""
    first = _SENTENCE_END.split(finding_cell.strip(), maxsplit=1)[0]
    if len(first) <= _SUMMARY_LIMIT:
        return first
    return first[: _SUMMARY_LIMIT - 1].rstrip() + "…"


def _entries(
    keys: Sequence[str], lines: Sequence[str], rows: Mapping[str, int]
) -> list[str]:
    entries = []
    for key in keys:
        cells = finding_status.cells(lines[rows[key] - 1])
        entries.append(f"- **{key}**: {summary(cells[1]) if len(cells) > 1 else ''}")
    return entries or ["- None."]


def render(
    ledger_text: str,
    *,
    source: str,
    cells: Sequence[Tier1Cell] = TIER1_CELLS,
    coordinates: Mapping[str, VerifiedSubsetCoordinate | None] | None = None,
) -> str:
    status = finding_status.project(ledger_text)
    if status.problems:
        raise ValueError("ledger is invalid: " + "; ".join(status.problems))
    mapped = tier1_coordinates(tuple(cells)) if coordinates is None else coordinates
    lines = ledger_text.splitlines()
    rows = {row.key: row.line for row in status.rows}
    classes = status.v01_classes
    groups: dict[str, list[str]] = {
        "blocking": [],
        "unclassified": [],
        "tier2": [],
        "later": [],
    }
    for key in status.open_keys:
        value = classes.get(key)
        group = {
            None: "unclassified",
            finding_status.V01Class.V0_1_BLOCKING: "blocking",
            finding_status.V01Class.TIER2: "tier2",
            finding_status.V01Class.POST_V0_1: "later",
        }[value]
        groups[group].append(key)
    out = [
        "# Molt v0.1 known issues",
        "",
        f"Generated by `tools/known_issues.py` from `{finding_status.LEDGER_PATH}` at "
        f"{source}. Do not edit by hand.",
        "",
        "## Tier 1 cells",
        "",
        "| Cell | Witness | Python | Backend | Target | Verified-subset coordinate |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for cell in cells:
        coordinate = mapped.get(cell.id)
        proof = (
            f"`{coordinate.id}`"
            if coordinate is not None
            else f"none: Molt does not admit target Python {cell.python}"
        )
        out.append(
            f"| `{cell.id}` | {cell.witness} | {cell.python} | {cell.backend} | "
            f"`{cell.artifact_target}` | {proof} |"
        )
    held = len(groups["blocking"]) + len(groups["unclassified"])
    out += [
        "",
        f"## Open rows that hold v0.1 ({held})",
        "",
        "Class `v0_1_blocking`: the row fails in a Tier 1 cell, is a safety defect, blocks "
        "Tier 1 installed delivery or guards a public performance claim.",
        "",
        *_entries(groups["blocking"], lines, rows),
    ]
    if groups["unclassified"]:
        out += [
            "",
            "Not yet classified; an unclassified row holds v0.1:",
            "",
            *_entries(groups["unclassified"], lines, rows),
        ]
    out += [
        "",
        f"## Tier 2 ({len(groups['tier2'])})",
        "",
        "These fail only in Tier 2 cells. They do not hold v0.1.",
        "",
        *_entries(groups["tier2"], lines, rows),
        "",
        f"## After v0.1 ({len(groups['later'])})",
        "",
        "Open work outside the v0.1 claim. It does not hold v0.1.",
        "",
        *_entries(groups["later"], lines, rows),
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--source-sha",
        help="read the ledger blob at this commit, as the release gate does",
    )
    parser.add_argument("--output", type=Path, help="write here instead of stdout")
    args = parser.parse_args(argv)
    if args.source_sha:
        from tools import release_exit_gate

        text = release_exit_gate.source_findings(ROOT, args.source_sha).ledger_blob
        source = f"commit `{args.source_sha}`"
    else:
        text = (ROOT / finding_status.LEDGER_PATH).read_text(encoding="utf-8")
        source = "the checkout"
    document = render(text, source=source)
    if args.output is None:
        sys.stdout.write(document)
    else:
        args.output.write_text(document, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
