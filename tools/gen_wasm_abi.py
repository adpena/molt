def _rust_builtin_default_value(expr: ast.expr) -> str:
    if isinstance(expr, ast.Tuple) and not expr.elts:
        return "GeneratedBuiltinDefaultValue::EmptyTuple"
    if isinstance(expr, ast.Name) and expr.id == "__molt_missing__":
        return "GeneratedBuiltinDefaultValue::Missing"
    if isinstance(expr, ast.Constant):
        value = expr.value
        if value is None:
            return "GeneratedBuiltinDefaultValue::None"
        if isinstance(value, bool):
            return f"GeneratedBuiltinDefaultValue::Bool({_rust_bool_lit(value)})"
        if isinstance(value, int):
            return f"GeneratedBuiltinDefaultValue::Int({value})"
        if isinstance(value, str):
            return f"GeneratedBuiltinDefaultValue::Str({_rust_str_lit(value)})"
    raise ValueError(
        "unsupported builtin default expression for WASM runtime callable "
        f"authority: {ast.dump(expr, include_attributes=False)}"
    )


def _rust_builtin_default_slice(exprs: list[ast.expr]) -> str:
    if not exprs:
        return "&[]"
    rendered = ", ".join(_rust_builtin_default_value(expr) for expr in exprs)
    return f"&[{rendered}]"


def _rust_builtin_kw_default_slice(pairs: list[tuple[str, ast.expr]]) -> str:
    if not pairs:
        return "&[]"
    rendered = ", ".join(
        f"({_rust_str_lit(name)}, {_rust_builtin_default_value(expr)})"
        for name, expr in pairs
    )
    return f"&[{rendered}]"


def _rust_str_slice(values: list[str]) -> str:
    if not values:
        return "&[]"
    rendered = ", ".join(_rust_str_lit(value) for value in values)
    return f"&[{rendered}]"


