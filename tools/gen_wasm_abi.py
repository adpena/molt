def _cache_input_files() -> tuple[Path, ...]:
    generator_pkg = Path(__file__).resolve().parent / "wasm_abi_gen"
    files = {
        Path(__file__).resolve(),
        BUILTIN_CALLABLES.resolve(),
        *(path.resolve() for path in generator_pkg.glob("*.py")),
        *(path.resolve() for path in generator_input_files()),
    }
    return tuple(sorted(files, key=lambda path: _cache_relative_path(path)))


def _cache_relative_path(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def _render_cache_key(rustfmt_version: str) -> str:
    digest = hashlib.sha256()
    digest.update(f"{GENERATOR_CACHE_VERSION}\n".encode())
    digest.update(f"python={sys.version}\n".encode())
    digest.update(f"rustfmt={rustfmt_version}\n".encode())
    for path in _cache_input_files():
        rel = _cache_relative_path(path)
        digest.update(f"path={rel}\n".encode())
        data = path.read_bytes()
        digest.update(f"len={len(data)}\n".encode())
        digest.update(data)
        digest.update(b"\n")
    for name, params, result in generator_runtime_export_signature_rows():
        digest.update(
            json.dumps(
                {
                    "runtime_export": name,
                    "params": list(params),
                    "result": result,
                },
                sort_keys=True,
                separators=(",", ":"),
            ).encode()
        )
        digest.update(b"\n")
    for name, symbol_kind in generator_cpython_abi_link_import_kinds():
        digest.update(
            json.dumps(
                {
                    "cpython_abi_link_import": name,
                    "symbol_kind": symbol_kind,
                },
                sort_keys=True,
                separators=(",", ":"),
            ).encode()
        )
        digest.update(b"\n")
    return digest.hexdigest()


def _cache_path(cache_key: str) -> Path:
    return WASM_ABI_GEN_CACHE / f"{cache_key}.json"


def _validate_cached_outputs(raw: object, cache_key: str) -> dict[Path, str] | None:
    if not isinstance(raw, dict):
        return None
    if raw.get("version") != GENERATOR_CACHE_VERSION or raw.get("key") != cache_key:
        return None
    outputs = raw.get("outputs")
    if not isinstance(outputs, dict):
        return None
    expected = {_cache_relative_path(path): path for path in OUTPUT_PATHS}
    if set(outputs) != set(expected):
        return None
    if not all(isinstance(text, str) for text in outputs.values()):
        return None
    return {path: outputs[name] for name, path in expected.items()}


def _load_render_cache(cache_key: str) -> dict[Path, str] | None:
    path = _cache_path(cache_key)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError, OSError):
        return None
    return _validate_cached_outputs(raw, cache_key)


def _store_render_cache(cache_key: str, outputs: Mapping[Path, str]) -> None:
    WASM_ABI_GEN_CACHE.mkdir(parents=True, exist_ok=True)
    path = _cache_path(cache_key)
    tmp_path = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    payload = {
        "version": GENERATOR_CACHE_VERSION,
        "key": cache_key,
        "outputs": {
            _cache_relative_path(output): text for output, text in outputs.items()
        },
    }
    tmp_path.write_text(json.dumps(payload, sort_keys=True), encoding="utf-8")
    tmp_path.replace(path)


def _py_tuple(vals: list[str]) -> str:
    if not vals:
        return "()"
    if len(vals) == 1:
        return f'("{vals[0]}",)'
    return "(" + ", ".join(f'"{val}"' for val in vals) + ")"


def _py_string(value: str) -> str:
    return repr(value)


def _rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _rust_pascal_variant(value: str) -> str:
    return "".join(part.capitalize() for part in value.split("_"))


def _runtime_import_variants(data: dict) -> Mapping[str, str]:
    variants: dict[str, str] = {}
    seen_variants: dict[str, str] = {}
    for entry in data["import"]:
        name = entry["name"]
        variant = _rust_pascal_variant(name)
        if variant in seen_variants:
            raise WasmAbiManifestError(
                "runtime import enum variant collision: "
                f"{seen_variants[variant]!r} and {name!r} both map to {variant!r}"
            )
        seen_variants[variant] = name
        variants[name] = variant
    return MappingProxyType(variants)


def _rust_runtime_import(variants: Mapping[str, str], import_name: str) -> str:
    return f"WasmRuntimeImport::{variants[import_name]}"


def _runtime_export_name(entry: dict) -> str:
    export_name = runtime_export_name(entry)
    if export_name is None:
        raise WasmAbiManifestError("runtime import entry must have a valid name")
    return export_name


