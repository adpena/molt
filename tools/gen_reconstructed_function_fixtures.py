#!/usr/bin/env python3
"""Project the CPython reference programs into tracked target-test projects."""

from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from tests.reconstructed_function_test_support import (  # noqa: E402
    ACTIVATION_TARGET_ROUTES,
    activation_target_sources,
)
from tools.generator_io import generator_main  # noqa: E402

FIXTURES = ROOT / "tests/fixtures/reconstructed_functions"
HEADER = "# @generated by tools/gen_reconstructed_function_fixtures.py; do not edit.\n"


def generated_outputs() -> dict[Path, str]:
    outputs = {
        FIXTURES / route / f"{module}.py": HEADER + source
        for route in ACTIVATION_TARGET_ROUTES
        for module, source in activation_target_sources(route).items()
    }
    outputs[FIXTURES / "TESTS.txt"] = HEADER + "".join(
        f"tests/fixtures/reconstructed_functions/{route}/main.py\n"
        for route in ACTIVATION_TARGET_ROUTES
    )
    obsolete = set(FIXTURES.rglob("*.py")) - outputs.keys()
    if obsolete:
        raise ValueError(
            "remove obsolete reconstructed-function fixtures: "
            + ", ".join(str(path.relative_to(ROOT)) for path in sorted(obsolete))
        )
    return outputs


def main(argv: list[str] | None = None) -> int:
    return generator_main(generated_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
