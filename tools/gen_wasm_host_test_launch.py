#!/usr/bin/env python3
"""Project the deny-policy WASM launch transport into molt-wasm-host test support.

Every host test manifest carries the launch a deployment compiled without
capability grants carries. The one authority for that transport is
molt.wasm_artifact.wasm_execution_manifest_launch of the deny policy
(molt.capability_manifest.resolve_runtime_policy_from_env({})), which
tests/wasm_execution_manifest.py also uses; the Rust tests read this projection
instead of a hand copy of its policy digest.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from tools.generator_io import generator_main  # noqa: E402

OUTPUT = _REPO_ROOT / "runtime/molt-wasm-host/tests/support/launch.rs"


def _deny_launch_environment() -> dict[str, str]:
    from molt.capability_manifest import resolve_runtime_policy_from_env
    from molt.wasm_artifact import wasm_execution_manifest_launch

    launch = wasm_execution_manifest_launch(resolve_runtime_policy_from_env({}))
    environment = launch["environment"]
    assert isinstance(environment, dict)
    return {str(name): str(value) for name, value in environment.items()}


def generated_outputs() -> dict[Path, str]:
    entries = "".join(
        f"        {json.dumps(name)}: {json.dumps(value)},\n"
        for name, value in sorted(_deny_launch_environment().items())
    )
    return {
        OUTPUT: (
            "// @generated by tools/gen_wasm_host_test_launch.py from\n"
            "// src/molt/capability_manifest.py and src/molt/wasm_artifact.py.\n"
            "// Do not edit; run python tools/gen_wasm_host_test_launch.py --write.\n"
            "\n"
            "//! The deployment launch transport for host test manifests: the deny\n"
            "//! policy's `launch`, which every deployment compiled without a\n"
            "//! capability grant carries. Unit tests include this file by path and\n"
            "//! integration tests through `support`.\n"
            "\n"
            "/// `launch.environment` of a deny-policy deployment.\n"
            "pub fn deny_launch_environment() -> serde_json::Value {\n"
            "    serde_json::json!({\n"
            f"{entries}"
            "    })\n"
            "}\n"
            "\n"
            "/// `launch` of a deny-policy deployment.\n"
            "pub fn deny_launch() -> serde_json::Value {\n"
            '    serde_json::json!({"environment": deny_launch_environment()})\n'
            "}\n"
        )
    }


def main(argv: list[str] | None = None) -> int:
    return generator_main(generated_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
