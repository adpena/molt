#!/usr/bin/env python3
"""Project the findings ledger into closed finding-identity types.

`docs/agent/V1_HANDOFF_FINDINGS.md` owns which findings exist and which are
open; `tools/finding_status.py` is its one reader. This generator renders that
projection as `Literal` types, so `ty` rejects a finding test or expectation
that cites a finding the ledger does not have or has closed. Closing a row
regenerates the type without it, and every test that still cites it fails the
type check and its runner in the same change.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from tools.finding_status import (  # noqa: E402
    STATE_FIXED,
    STATE_OPEN,
    finding_sort_key,
    read_ledger,
)
from tools.generator_io import generator_main  # noqa: E402

OUTPUT = Path("tests/findings/finding_ids.py")


def _quoted(key: str) -> str:
    """A string literal in the repository's format (ruff's quote preference)."""
    quote = "'" if key.count('"') > key.count("'") else '"'
    body = key.replace("\\", "\\\\").replace(quote, "\\" + quote)
    literal = f"{quote}{body}{quote}"
    if ast.literal_eval(literal) != key:
        raise ValueError(f"finding key {key!r} has no plain string literal form")
    return literal


def _literal(name: str, keys: list[str]) -> str:
    # The release that closes the last open row leaves an empty set; an empty
    # Literal is not a type, and Never admits no value, as intended.
    if not keys:
        return f"{name} = Never\n"
    members = "".join(f"    {_quoted(key)},\n" for key in keys)
    return f"{name} = Literal[\n{members}]\n"


def render(root: Path = _REPO_ROOT) -> str:
    status = read_ledger(root)
    if status.problems:
        raise ValueError(
            "the findings ledger has structural problems; fix them before "
            "projecting finding identities:\n" + "\n".join(status.problems)
        )
    by_state: dict[str, list[str]] = {STATE_OPEN: [], STATE_FIXED: []}
    for row in status.rows:
        by_state[row.state].append(row.key)
    open_keys = sorted(by_state[STATE_OPEN], key=finding_sort_key)
    fixed_keys = sorted(by_state[STATE_FIXED], key=finding_sort_key)
    names = {"get_args"}
    if open_keys or fixed_keys:
        names.add("Literal")
    if not open_keys or not fixed_keys:
        names.add("Never")
    return (
        "# @generated by tools/gen_finding_ids.py from "
        "docs/agent/V1_HANDOFF_FINDINGS.md.\n"
        "# Do not edit; run python tools/gen_finding_ids.py --write.\n"
        '"""The finding identities of the V1 findings ledger, as closed types."""\n'
        "\n"
        f"from typing import {', '.join(sorted(names))}\n"
        "\n"
        f"{_literal('OpenFindingId', open_keys)}"
        "\n"
        f"{_literal('FixedFindingId', fixed_keys)}"
        "\n"
        "OPEN_FINDING_IDS: frozenset[str] = frozenset(get_args(OpenFindingId))\n"
        "FIXED_FINDING_IDS: frozenset[str] = frozenset(get_args(FixedFindingId))\n"
    )


def generated_outputs() -> dict[Path, str]:
    return {_REPO_ROOT / OUTPUT: render()}


def main(argv: list[str] | None = None) -> int:
    return generator_main(generated_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
