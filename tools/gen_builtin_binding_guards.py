#!/usr/bin/env python3
"""Generate the builtin binding guard table from one TOML authority.

``runtime/builtin_binding_guards.toml`` lists the builtin names that a
function can call through a guarded specialization (HF-79). Each name owns one
bit, in table order. The compiler folds the bits of the names one guard covers
into a mask; the runtime maps a namespace key to its bit when a module or the
builtins namespace binds it. Both sides read these generated tables, so the
bit assignment cannot drift.

Usage::

    python tools/gen_builtin_binding_guards.py --write
    python tools/gen_builtin_binding_guards.py --check
"""

from __future__ import annotations

import keyword
import tomllib
from dataclasses import dataclass
from pathlib import Path

from generator_io import generator_main, rustfmt_source

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "runtime" / "builtin_binding_guards.toml"
OUT_PYTHON = (
    ROOT / "src" / "molt" / "compiler_analysis" / "builtin_binding_guards_generated.py"
)
OUT_RUST = (
    ROOT
    / "runtime"
    / "molt-runtime"
    / "src"
    / "builtins"
    / "binding_guards_generated.rs"
)
OUTPUTS = (OUT_PYTHON, OUT_RUST)

# Compiled code passes the mask as an inline int: 47-bit signed payload.
MAX_NAMES = 46


class SchemaError(ValueError):
    """The checked-in guard authority is inconsistent."""


@dataclass(frozen=True)
class Schema:
    names: tuple[str, ...]

    @property
    def all_mask(self) -> int:
        return (1 << len(self.names)) - 1


def load_schema(path: Path = SOURCE) -> Schema:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        raise SchemaError("schema_version must be 1")
    names = data.get("names")
    if not isinstance(names, list) or not names:
        raise SchemaError("names must be a non-empty array")
    if len(names) > MAX_NAMES:
        raise SchemaError(f"at most {MAX_NAMES} names fit an inline-int mask")
    seen: set[str] = set()
    for name in names:
        if not isinstance(name, str) or not name.isidentifier():
            raise SchemaError(f"name {name!r} is not an identifier")
        if keyword.iskeyword(name):
            raise SchemaError(f"name {name!r} is a keyword")
        if name in seen:
            raise SchemaError(f"name {name!r} repeats")
        seen.add(name)
    if list(names) != sorted(names):
        raise SchemaError("names must be sorted; a bit is the name's table index")
    unknown = set(data) - {"schema_version", "names"}
    if unknown:
        raise SchemaError(f"unknown keys: {sorted(unknown)}")
    return Schema(tuple(names))


def render_python(schema: Schema) -> str:
    lines = [
        "# @generated by tools/gen_builtin_binding_guards.py from\n",
        "# runtime/builtin_binding_guards.toml. DO NOT EDIT BY HAND.\n",
        '"""Builtin names a function can call behind a binding guard (HF-79)."""\n',
        "\n",
        "from __future__ import annotations\n",
        "\n",
        "from types import MappingProxyType\n",
        "from typing import Final, Mapping\n",
        "\n",
        "BUILTIN_BINDING_GUARD_BITS: Final[Mapping[str, int]] = MappingProxyType(\n",
        "    {\n",
    ]
    lines.extend(
        f'        "{name}": 1 << {bit},\n' for bit, name in enumerate(schema.names)
    )
    lines += [
        "    }\n",
        ")\n",
        f"BUILTIN_BINDING_GUARD_ALL_MASK: Final[int] = 0x{schema.all_mask:X}\n",
        "\n",
        "__all__ = [\n",
        '    "BUILTIN_BINDING_GUARD_ALL_MASK",\n',
        '    "BUILTIN_BINDING_GUARD_BITS",\n',
        "]\n",
    ]
    return "".join(lines)


def render_rust(schema: Schema) -> str:
    arms = "".join(
        f'        b"{name}" => 1 << {bit},\n' for bit, name in enumerate(schema.names)
    )
    names = "".join(f'    "{name}",\n' for name in schema.names)
    source = (
        "// @generated by tools/gen_builtin_binding_guards.py from\n"
        "// runtime/builtin_binding_guards.toml. DO NOT EDIT BY HAND.\n"
        "\n"
        "/// Guarded builtin names; a name's bit is its index.\n"
        f"pub(crate) const BUILTIN_BINDING_GUARD_NAMES: [&str; {len(schema.names)}] = [\n"
        f"{names}"
        "];\n"
        "\n"
        "/// Every guard bit.\n"
        f"pub(crate) const BUILTIN_BINDING_GUARD_ALL_MASK: u64 = {schema.all_mask:#x};\n"
        "\n"
        "/// The guard bit of an exact `str` namespace key, or zero.\n"
        "#[inline]\n"
        "pub(crate) fn builtin_binding_guard_bit(name: &[u8]) -> u64 {\n"
        "    match name {\n"
        f"{arms}"
        "        _ => 0,\n"
        "    }\n"
        "}\n"
    )
    return rustfmt_source(source, label=str(OUT_RUST.relative_to(ROOT)))


def render_all(schema: Schema) -> dict[Path, str]:
    return {OUT_PYTHON: render_python(schema), OUT_RUST: render_rust(schema)}


def generated_outputs() -> dict[Path, str]:
    """Each output path mapped to its exact generated text."""
    return render_all(load_schema())


def main(argv: list[str] | None = None) -> int:
    return generator_main(generated_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
