#!/usr/bin/env python3
"""Generate target-version Unicode widths; never query host Unicode at runtime."""

from __future__ import annotations

import json
import os
from contextlib import ExitStack
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import harness_memory_guard  # noqa: E402
from generator_io import generator_main  # noqa: E402
from molt.target_python import SUPPORTED_TARGET_PYTHON_SHORT_VERSIONS  # noqa: E402

OUTPUT = ROOT / "runtime/molt-runtime/src/object/unicode_width_generated.rs"
QUERY = """
import json, sys, unicodedata
ranges = []
for code in range(0x110000):
    width = unicodedata.east_asian_width(chr(code))
    if ranges and ranges[-1][2] == width:
        ranges[-1][1] = code
    else:
        ranges.append([code, code, width])
print(json.dumps(dict(python=f'{sys.version_info.major}.{sys.version_info.minor}',
                     unicode=unicodedata.unidata_version, ranges=ranges,
                     executable=sys.executable,
                     startup=[sys.flags.isolated, sys.flags.no_site, sys.flags.dont_write_bytecode])))
"""


def render(*, python_runtimes) -> str:
    lines = [
        "// Generated by tools/gen_unicode_width.py; do not edit.",
        "// Complete CPython East_Asian_Width facts, including unassigned code points.",
        "pub(crate) type WidthRanges = &'static [(u32, u32, &'static str)];",
    ]
    versions = []
    if set(python_runtimes) != set(SUPPORTED_TARGET_PYTHON_SHORT_VERSIONS):
        raise ValueError("Unicode generation requires every admitted target runtime")
    for version in SUPPORTED_TARGET_PYTHON_SHORT_VERSIONS:
        selected, admission = python_runtimes[version]
        launch = selected["launch_argv"]
        environment = {**os.environ, "MOLT_BUILD_PYTHON": launch[0]}
        if admission.capture(environment)["runtime"] != selected["runtime"]:
            raise ValueError(f"CPython {version} changed after generator admission")
        result = harness_memory_guard.guarded_completed_process(
            [*launch, "-c", QUERY],
            prefix="MOLT_TEST_SUITE",
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=30,
        )
        if admission.capture(environment)["runtime"] != selected["runtime"]:
            raise ValueError(f"CPython {version} changed during Unicode query")
        if result.returncode:
            raise RuntimeError(
                f"CPython {version} Unicode capture failed: {result.stderr}"
            )
        data = json.loads(result.stdout)
        if data["executable"] != launch[0] or data["startup"] != [1, 1, 1]:
            raise ValueError(f"CPython {version} query used an unadmitted startup")
        if data["python"] != version:
            raise ValueError(f"requested CPython {version}, got {data['python']}")
        name = "WIDTH_" + version.replace(".", "_")
        lines.append(f"const {name}: WidthRanges = &[")
        expected = 0
        for lo, hi, width in data["ranges"]:
            if (
                lo != expected
                or not lo <= hi < 0x110000
                or width not in {"N", "Na", "A", "H", "W", "F"}
            ):
                raise ValueError(f"invalid CPython {version} width ranges")
            lines.append(f'    ({lo}, {hi}, "{width}"),')
            expected = hi + 1
        if expected != 0x110000:
            raise ValueError(f"incomplete CPython {version} width coverage")
        lines.append("];")
        major, minor = version.split(".")
        if major != "3":
            raise ValueError("extend the runtime target authority for a new major")
        versions.append(f'        {minor} => Some(("{data["unicode"]}", {name})),')
    lines.extend(
        [
            "pub(crate) fn for_minor(minor: i64) -> Option<(&'static str, WidthRanges)> {",
            "    match minor {",
            *versions,
            "        _ => None,",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generated_outputs(*, python_runtimes) -> dict[Path, str]:
    """Each output path mapped to its exact generated text."""
    return {OUTPUT: render(python_runtimes=python_runtimes)}


def main(argv: list[str] | None = None) -> int:
    def admitted_outputs() -> dict[Path, str]:
        from tools.generators import admit_generators, manifest_generators

        with ExitStack() as stack:
            _, bindings = admit_generators(
                [
                    row
                    for row in manifest_generators(
                        ROOT / "tools/generator_manifest.toml"
                    )
                    if row.tool == "tools/gen_unicode_width.py"
                ],
                root=ROOT,
                runtime_stack=stack,
            )
            return generated_outputs(
                python_runtimes=bindings["tools/gen_unicode_width.py"]
            )

    return generator_main(admitted_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
