#!/usr/bin/env python3
"""Generate target-version Unicode widths; never query host Unicode at runtime."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import harness_memory_guard  # noqa: E402
from generator_io import generated_file_matches, write_generated_text  # noqa: E402
from molt.target_python import SUPPORTED_TARGET_PYTHON_SHORT_VERSIONS  # noqa: E402

OUTPUT = ROOT / "runtime/molt-runtime/src/object/unicode_width_generated.rs"
QUERY = """
import json, sys, unicodedata
ranges = []
for code in range(0x110000):
    width = unicodedata.east_asian_width(chr(code))
    if ranges and ranges[-1][2] == width:
        ranges[-1][1] = code
    else:
        ranges.append([code, code, width])
print(json.dumps(dict(python=f'{sys.version_info.major}.{sys.version_info.minor}',
                     unicode=unicodedata.unidata_version, ranges=ranges)))
"""


def render() -> str:
    lines = [
        "// Generated by tools/gen_unicode_width.py; do not edit.",
        "// Complete CPython East_Asian_Width facts, including unassigned code points.",
        "pub(crate) type WidthRanges = &'static [(u32, u32, &'static str)];",
    ]
    versions = []
    for version in SUPPORTED_TARGET_PYTHON_SHORT_VERSIONS:
        result = harness_memory_guard.guarded_completed_process(
            [
                "uv",
                "run",
                "--no-project",
                "--no-python-downloads",
                "--python",
                version,
                "python",
                "-I",
                "-S",
                "-c",
                QUERY,
            ],
            prefix="MOLT_TEST_SUITE",
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=30,
        )
        if result.returncode:
            raise RuntimeError(
                f"CPython {version} Unicode capture failed: {result.stderr}"
            )
        data = json.loads(result.stdout)
        if data["python"] != version:
            raise ValueError(f"requested CPython {version}, got {data['python']}")
        name = "WIDTH_" + version.replace(".", "_")
        lines.append(f"const {name}: WidthRanges = &[")
        expected = 0
        for lo, hi, width in data["ranges"]:
            if (
                lo != expected
                or not lo <= hi < 0x110000
                or width not in {"N", "Na", "A", "H", "W", "F"}
            ):
                raise ValueError(f"invalid CPython {version} width ranges")
            lines.append(f'    ({lo}, {hi}, "{width}"),')
            expected = hi + 1
        if expected != 0x110000:
            raise ValueError(f"incomplete CPython {version} width coverage")
        lines.append("];")
        major, minor = version.split(".")
        if major != "3":
            raise ValueError("extend the runtime target authority for a new major")
        versions.append(f'        {minor} => Some(("{data["unicode"]}", {name})),')
    lines.extend(
        [
            "pub(crate) fn for_minor(minor: i64) -> Option<(&'static str, WidthRanges)> {",
            "    match minor {",
            *versions,
            "        _ => None,",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render()
    if args.check:
        if not generated_file_matches(OUTPUT, output):
            print(f"stale Unicode width authority: {OUTPUT}", file=sys.stderr)
            return 1
    else:
        write_generated_text(OUTPUT, output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
