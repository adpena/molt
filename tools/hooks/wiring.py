"""The Claude Code hook wiring: one declaration, projected into its consumers.

``HOOKS`` names each hook Claude Code starts: its event, its matcher, the
``tools/hooks/<hook>.py`` script and its timeout. ``tools/gen_claude_hooks.py``
projects it into ``.claude/settings.json`` (what Claude Code reads) and
``tools/hooks/prefilter.generated.sh`` (the bash_guard token test ``run.sh``
applies before it starts Python). The liveness check and the tests read this
module, never the settings text.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Literal

HookEvent = Literal["SessionStart", "PreToolUse", "Stop"]

SETTINGS_SCHEMA = "https://json.schemastore.org/claude-code-settings.json"
LAUNCHER = '"${CLAUDE_PROJECT_DIR}/tools/hooks/run.sh"'


@dataclass(frozen=True, slots=True)
class HookCommand:
    event: HookEvent
    matcher: str | None
    hook: str
    timeout_s: int

    @property
    def module(self) -> str:
        return f"tools.hooks.{self.hook}"

    @property
    def command(self) -> str:
        # `sh` on a missing file exits 127; the guard makes it a visible,
        # non-blocking exit 1 (exit 2 would block a PreToolUse tool call).
        return f"[ -f {LAUNCHER} ] || exit 1; sh {LAUNCHER} {self.hook}"


HOOKS: tuple[HookCommand, ...] = (
    HookCommand("SessionStart", None, "session_digest", 15),
    HookCommand("PreToolUse", "Bash", "bash_guard", 15),
    HookCommand("Stop", None, "stop_gates", 20),
)


def settings_document() -> str:
    """The exact text of ``.claude/settings.json``."""
    events: dict[str, list[dict[str, object]]] = {}
    for hook in HOOKS:
        group: dict[str, object] = {}
        if hook.matcher is not None:
            group["matcher"] = hook.matcher
        group["hooks"] = [
            {"type": "command", "command": hook.command, "timeout": hook.timeout_s}
        ]
        events.setdefault(hook.event, []).append(group)
    document = {"$schema": SETTINGS_SCHEMA, "hooks": events}
    return json.dumps(document, indent=2) + "\n"


def prefilter_script(tokens: tuple[str, ...]) -> str:
    """The POSIX ``sh`` function ``run.sh`` sources: a case-insensitive test
    for any bash_guard token in the raw hook payload."""

    def insensitive(token: str) -> str:
        return "".join(f"[{c.lower()}{c.upper()}]" if c.isalpha() else c for c in token)

    arms = " | ".join(f"*{insensitive(token)}*" for token in tokens)
    return (
        "# @generated by tools/gen_claude_hooks.py from "
        "tools/hooks/bash_guard.py PREFILTER_TOKENS; do not edit.\n"
        "# Sourced by tools/hooks/run.sh: succeed when any token appears, in any\n"
        "# case, anywhere in the payload.\n"
        "molt_hook_prefilter() {\n"
        "    case $1 in\n"
        f"        {arms}) return 0 ;;\n"
        "    esac\n"
        "    return 1\n"
        "}\n"
    )
