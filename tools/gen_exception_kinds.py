#!/usr/bin/env python3
"""Generate the typed exception identity from runtime/exception_kinds.toml.

The table is the one authority for which exception classes the runtime can
raise, match or construct (HF-207). It renders:

  - ``runtime/molt-obj-model/src/exception_kinds_generated.rs``: the closed
    ``BuiltinExc``, ``ModuleExc`` and ``ExcKind`` types over one dense ``u16``
    code space, the builtin schema rows (``BUILTIN_EXCEPTION_SPECS``), the
    module binding rows and the per-owner member lists;
  - ``src/molt/frontend/exception_kinds_generated.py``: the builtin codes the
    frontend's constructor and match tags carry.

A module row's class is taken from its owner on first raise and checked
against the row (see ``docs/design/foundation/exception_kinds.md``).

Usage::

    python tools/gen_exception_kinds.py --write
    python tools/gen_exception_kinds.py --check
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from tools.generator_io import generator_main, rustfmt_sources  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "runtime" / "exception_kinds.toml"
OUT_MODEL = ROOT / "runtime" / "molt-obj-model" / "src" / "exception_kinds_generated.rs"
OUT_PYTHON = ROOT / "src" / "molt" / "frontend" / "exception_kinds_generated.py"
OUTPUTS = (OUT_MODEL, OUT_PYTHON)

HEADER = (
    "// @generated by tools/gen_exception_kinds.py from runtime/exception_kinds.toml.\n"
    "// DO NOT EDIT. Regenerate with `python tools/gen_exception_kinds.py --write`.\n"
)
LAYOUT_ROOTS = {
    "BaseExceptionGroup",
    "SyntaxError",
    "ImportError",
    "UnicodeDecodeError",
    "UnicodeEncodeError",
    "UnicodeTranslateError",
    "SystemExit",
    "OSError",
    "StopIteration",
    "NameError",
    "AttributeError",
}
STR_SLOTS = {
    "Base",
    "Group",
    "KeyError",
    "Syntax",
    "Import",
    "OSError",
    "UnicodeDecode",
    "UnicodeEncode",
    "UnicodeTranslate",
}
BUILTIN_KEYS = {
    "name",
    "variant",
    "bases",
    "layout_root",
    "str_slot",
    "declares_repr",
    "module",
    "builtin_binding",
    "heap_type",
    "since_minor",
    "name_lookup",
}
ALIAS_KEYS = {"name", "canonical", "windows_only"}
MODULE_KEYS = {"owner", "name", "variant", "base"}
# The u16 code space leaves room for growth; codes are positional, so the
# frontend and runtime agree by construction, not by a second table.
MAX_KINDS = 1 << 16
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_OWNER = re.compile(r"^[a-z_][a-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$")


class ExceptionKindTableError(ValueError):
    """The exception identity table violates its schema."""


def _fail(message: str) -> None:
    raise ExceptionKindTableError(message)


def owner_variant(owner: str) -> str:
    """The ``ModuleExcOwner`` variant of an owning module."""
    return "".join(
        part[:1].upper() + part[1:] for part in re.split(r"[._]", owner) if part
    )


def load_table(path: Path = TABLE) -> dict:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1:
        _fail("exception_kinds.toml schema_version must be 1")
    unknown = set(data) - {"schema_version", "builtin", "alias", "module"}
    if unknown:
        _fail(f"unknown top-level keys: {sorted(unknown)}")
    builtins = [dict(row) for row in data.get("builtin", [])]
    aliases = [dict(row) for row in data.get("alias", [])]
    modules = [dict(row) for row in data.get("module", [])]
    variants: set[str] = set()
    names: set[str] = set()
    for row in builtins:
        extra = set(row) - BUILTIN_KEYS
        if extra:
            _fail(f"builtin {row.get('name')!r} has unknown keys {sorted(extra)}")
        name = row["name"]
        row.setdefault("variant", name)
        row.setdefault("module", "builtins")
        row.setdefault("declares_repr", False)
        row.setdefault("heap_type", row["module"] != "builtins")
        row.setdefault("builtin_binding", row["module"] == "builtins")
        row.setdefault("since_minor", 12)
        row.setdefault("name_lookup", True)
        if not _IDENT.match(name) or not _IDENT.match(row["variant"]):
            _fail(f"builtin {name!r} needs identifier name and variant")
        if row["variant"] in variants:
            _fail(f"duplicate variant {row['variant']!r}")
        variants.add(row["variant"])
        if row["name_lookup"]:
            if name in names:
                _fail(f"duplicate looked-up builtin name {name!r}")
            names.add(name)
        bases = row["bases"]
        if len(bases) > 2 or (not bases and name != "BaseException"):
            _fail(f"builtin {name!r} needs one or two bases")
        for base in bases:
            if base not in names:
                _fail(f"builtin {name!r} names base {base!r} before its row")
        if row.get("layout_root") not in (None, *LAYOUT_ROOTS):
            _fail(f"builtin {name!r} has unknown layout_root")
        if row.get("str_slot") not in (None, *STR_SLOTS):
            _fail(f"builtin {name!r} has unknown str_slot")
        if row["builtin_binding"] and row["module"] != "builtins":
            _fail(f"builtin {name!r} binds in builtins but belongs to {row['module']}")
    for row in aliases:
        extra = set(row) - ALIAS_KEYS
        if extra:
            _fail(f"alias {row.get('name')!r} has unknown keys {sorted(extra)}")
        row.setdefault("windows_only", False)
        if row["name"] in names or row["canonical"] not in names:
            _fail(f"alias {row['name']!r} must name a new spelling of a builtin row")
        names.add(row["name"])
    builtin_names = {row["name"] for row in builtins if row["name_lookup"]}
    seen_qualified: set[tuple[str, str]] = set()
    for row in modules:
        extra = set(row) - MODULE_KEYS
        if extra or set(row) != MODULE_KEYS:
            _fail(f"module row {row!r} must have exactly {sorted(MODULE_KEYS)}")
        if not _OWNER.match(row["owner"]) or not _IDENT.match(row["name"]):
            _fail(f"module row {row!r} needs a dotted owner and identifier name")
        if row["variant"] in variants:
            _fail(f"duplicate variant {row['variant']!r}")
        variants.add(row["variant"])
        key = (row["owner"], row["name"])
        if key in seen_qualified:
            _fail(f"duplicate module row {key}")
        seen_qualified.add(key)
        if row["base"] not in builtin_names:
            _fail(f"module row {key} names unknown base {row['base']!r}")
    if len(builtins) + len(modules) + 1 > MAX_KINDS:
        _fail("exception kinds exceed the u16 code space")
    return {"builtin": builtins, "alias": aliases, "module": modules}


def owners(table: dict) -> list[str]:
    """Owning modules in first-row order."""
    seen: dict[str, None] = {}
    for row in table["module"]:
        seen.setdefault(row["owner"], None)
    return list(seen)


def _rust_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_model(table: dict) -> str:
    builtins = table["builtin"]
    modules = table["module"]
    count_builtin = len(builtins)
    count_module = len(modules)
    out: list[str] = [HEADER]
    out.append(
        "use crate::exception_layout::{BuiltinExceptionSpec, ExceptionBaseSpec, "
        "ExceptionLayoutRoot, ExceptionStrSlot, exception_alias, exception_spec};\n"
    )
    out.append(
        "/// Exception classes the runtime constructs itself. The discriminant is the\n"
        "/// `ExcKind` code; code 0 is reserved so no valid kind is zero.\n"
        "#[repr(u16)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\n"
        "pub enum BuiltinExc {\n"
    )
    for index, row in enumerate(builtins):
        out.append(f"    {row['variant']} = {index + 1},\n")
    out.append("}\n\n")
    out.append(
        "/// Exception classes a Python stdlib module defines; the runtime takes\n"
        "/// each from its owner on first raise.\n"
        "/// Discriminants continue the `ExcKind` code space after `BuiltinExc`.\n"
        "#[repr(u16)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\n"
        "pub enum ModuleExc {\n"
    )
    for index, row in enumerate(modules):
        out.append(f"    {row['variant']} = {count_builtin + index + 1},\n")
    out.append("}\n\n")
    owner_list = owners(table)
    out.append(
        "/// Python modules that own `ModuleExc` rows.\n"
        "#[repr(u16)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n"
        "pub enum ModuleExcOwner {\n"
    )
    for owner in owner_list:
        out.append(f"    {owner_variant(owner)},\n")
    out.append("}\n\n")
    out.append(
        "/// One typed exception identity: a runtime-constructed class or a\n"
        "/// module-bound class. Raises carry this, never a spelling.\n"
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n"
        "pub enum ExcKind {\n    Builtin(BuiltinExc),\n    Module(ModuleExc),\n}\n\n"
    )
    out.append(
        "impl From<BuiltinExc> for ExcKind {\n"
        "    #[inline]\n    fn from(kind: BuiltinExc) -> Self {\n        Self::Builtin(kind)\n    }\n}\n\n"
        "impl From<ModuleExc> for ExcKind {\n"
        "    #[inline]\n    fn from(kind: ModuleExc) -> Self {\n        Self::Module(kind)\n    }\n}\n\n"
    )
    # BuiltinExc
    out.append("impl BuiltinExc {\n")
    out.append(f"    pub const COUNT: usize = {count_builtin};\n")
    out.append("    pub const ALL: [Self; Self::COUNT] = [\n")
    for row in builtins:
        out.append(f"        Self::{row['variant']},\n")
    out.append("    ];\n\n")
    out.append(
        "    /// The class `__name__`.\n"
        "    pub const fn name(self) -> &'static str {\n        match self {\n"
    )
    for row in builtins:
        out.append(f"            Self::{row['variant']} => {_rust_str(row['name'])},\n")
    out.append("        }\n    }\n\n")
    out.append(
        "    /// The class `__module__`.\n"
        "    pub const fn module(self) -> &'static str {\n        match self {\n"
    )
    for row in builtins:
        out.append(
            f"            Self::{row['variant']} => {_rust_str(row['module'])},\n"
        )
    out.append("        }\n    }\n\n")
    out.append(
        "    /// The canonical schema row for this class.\n"
        "    #[inline]\n    pub const fn spec(self) -> &'static BuiltinExceptionSpec {\n"
        "        &BUILTIN_EXCEPTION_SPECS[self as usize - 1]\n    }\n\n"
    )
    out.append(
        "    /// Resolve a canonical builtin spelling at a string boundary (the\n"
        "    /// C API and the string `exception_new` op kind). Aliases resolve\n"
        "    /// through `builtin_exception_spec`.\n"
        "    pub fn from_name(name: &str) -> Option<Self> {\n        match name {\n"
    )
    for row in builtins:
        if row["name_lookup"]:
            out.append(
                f"            {_rust_str(row['name'])} => Some(Self::{row['variant']}),\n"
            )
    out.append("            _ => None,\n        }\n    }\n}\n\n")
    out.append(
        "/// Diagnostics print the class `__name__`, never a lookup key.\n"
        "impl core::fmt::Display for BuiltinExc {\n"
        "    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {\n"
        "        f.write_str(self.name())\n    }\n}\n\n"
        "/// Diagnostics print `owner.qualname`.\n"
        "impl core::fmt::Display for ModuleExc {\n"
        "    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {\n"
        "        let spec = self.spec();\n"
        '        write!(f, "{}.{}", spec.owner.module(), spec.name)\n    }\n}\n\n'
    )
    # ModuleExc
    out.append("impl ModuleExc {\n")
    out.append(f"    pub const COUNT: usize = {count_module};\n")
    out.append("    pub const ALL: [Self; Self::COUNT] = [\n")
    for row in modules:
        out.append(f"        Self::{row['variant']},\n")
    out.append("    ];\n\n")
    out.append(
        "    /// The binding row for this class.\n"
        "    #[inline]\n    pub const fn spec(self) -> &'static ModuleExceptionSpec {\n"
        "        &MODULE_EXCEPTION_SPECS[self as usize - BuiltinExc::COUNT - 1]\n    }\n}\n\n"
    )
    # ModuleExcOwner
    out.append("impl ModuleExcOwner {\n")
    out.append(f"    pub const COUNT: usize = {len(owner_list)};\n")
    out.append("    pub const ALL: [Self; Self::COUNT] = [\n")
    for owner in owner_list:
        out.append(f"        Self::{owner_variant(owner)},\n")
    out.append("    ];\n\n")
    out.append(
        "    /// The owning module's `__name__`.\n"
        "    pub const fn module(self) -> &'static str {\n        match self {\n"
    )
    for owner in owner_list:
        out.append(f"            Self::{owner_variant(owner)} => {_rust_str(owner)},\n")
    out.append("        }\n    }\n\n")
    out.append(
        "    /// The rows this module owns, in table order.\n"
        "    pub const fn members(self) -> &'static [ModuleExc] {\n        match self {\n"
    )
    for owner in owner_list:
        members = ", ".join(
            f"ModuleExc::{row['variant']}" for row in modules if row["owner"] == owner
        )
        out.append(f"            Self::{owner_variant(owner)} => &[{members}],\n")
    out.append("        }\n    }\n}\n\n")
    # ExcKind
    out.append("impl ExcKind {\n")
    out.append(
        "    pub const COUNT: usize = BuiltinExc::COUNT + ModuleExc::COUNT;\n"
        "    /// Slot tables index by code; slot 0 is the reserved invalid code.\n"
        "    pub const SLOTS: usize = Self::COUNT + 1;\n\n"
    )
    out.append(
        "    /// The dense `u16` code: the slot index and the bridge transport.\n"
        "    #[inline]\n    pub const fn code(self) -> u16 {\n        match self {\n"
        "            Self::Builtin(kind) => kind as u16,\n"
        "            Self::Module(kind) => kind as u16,\n        }\n    }\n\n"
        "    #[inline]\n    pub const fn from_code(code: u16) -> Option<Self> {\n"
        "        let index = code as usize;\n"
        "        if index == 0 {\n            None\n"
        "        } else if index <= BuiltinExc::COUNT {\n"
        "            Some(Self::Builtin(BuiltinExc::ALL[index - 1]))\n"
        "        } else if index <= Self::COUNT {\n"
        "            Some(Self::Module(ModuleExc::ALL[index - BuiltinExc::COUNT - 1]))\n"
        "        } else {\n            None\n        }\n    }\n\n"
        "    /// `(module, qualname)` of the class, for diagnostics only.\n"
        "    pub const fn qualified_name(self) -> (&'static str, &'static str) {\n"
        "        match self {\n"
        "            Self::Builtin(kind) => (kind.module(), kind.name()),\n"
        "            Self::Module(kind) => {\n"
        "                let spec = kind.spec();\n"
        "                (spec.owner.module(), spec.name)\n"
        "            }\n        }\n    }\n}\n\n"
    )
    out.append(
        "/// A module-owned class: `owner.name`, checked for its `__module__`,\n"
        "/// `__qualname__` and that it derives from `base`.\n"
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n"
        "pub struct ModuleExceptionSpec {\n"
        "    pub owner: ModuleExcOwner,\n    pub name: &'static str,\n"
        "    pub base: BuiltinExc,\n}\n\n"
    )
    out.append(
        "pub const MODULE_EXCEPTION_SPECS: [ModuleExceptionSpec; ModuleExc::COUNT] = [\n"
    )
    for row in modules:
        out.append(
            "    ModuleExceptionSpec {\n"
            f"        owner: ModuleExcOwner::{owner_variant(row['owner'])},\n"
            f"        name: {_rust_str(row['name'])},\n"
            f"        base: BuiltinExc::{_variant_of(builtins, row['base'])},\n"
            "    },\n"
        )
    out.append("];\n\n")
    # Builtin spec rows: canonical rows in BuiltinExc order, then aliases.
    total = count_builtin + len(table["alias"])
    out.append(
        "/// Canonical rows in `BuiltinExc` order, then alias spellings.\n"
        f"pub(crate) const BUILTIN_EXCEPTION_SPECS: [BuiltinExceptionSpec; {total}] = [\n"
    )
    for row in builtins:
        bases = row["bases"]
        if not bases:
            base = "ExceptionBaseSpec::Root"
        elif len(bases) == 1:
            base = f"ExceptionBaseSpec::One({_rust_str(bases[0])})"
        else:
            base = (
                f"ExceptionBaseSpec::Two({_rust_str(bases[0])}, {_rust_str(bases[1])})"
            )
        root = (
            f"Some(ExceptionLayoutRoot::{row['layout_root']})"
            if row.get("layout_root")
            else "None"
        )
        expr = (
            f"    exception_spec({_rust_str(row['name'])}, BuiltinExc::{row['variant']}, "
            f"{base}, {root})"
        )
        if row.get("str_slot"):
            expr += f"\n        .with_str_slot(ExceptionStrSlot::{row['str_slot']})"
        if row["declares_repr"]:
            expr += "\n        .with_repr()"
        if row["heap_type"]:
            expr += f"\n        .with_heap_class({_rust_str(row['module'])})"
        if not row["builtin_binding"]:
            expr += "\n        .without_builtin_binding()"
        if row["since_minor"] != 12:
            expr += f"\n        .since_python_minor({row['since_minor']})"
        if not row["name_lookup"]:
            expr += "\n        .without_name_lookup()"
        out.append(expr + ",\n")
    for row in table["alias"]:
        expr = f"    exception_alias({_rust_str(row['name'])}, {_rust_str(row['canonical'])})"
        if row["windows_only"]:
            expr += ".on_windows_only()"
        out.append(expr + ",\n")
    out.append("];\n\n")
    out.append(
        "/// Resolve a builtin alias spelling to its schema row.\n"
        "pub(crate) fn builtin_exception_alias(name: &str) -> Option<&'static BuiltinExceptionSpec> {\n"
        "    match name {\n"
    )
    for index, row in enumerate(table["alias"]):
        out.append(
            f"        {_rust_str(row['name'])} => Some(&BUILTIN_EXCEPTION_SPECS[{count_builtin + index}]),\n"
        )
    out.append("        _ => None,\n    }\n}\n")
    return "".join(out)


def _variant_of(builtins: list[dict], name: str) -> str:
    for row in builtins:
        if row["name"] == name and row["name_lookup"]:
            return row["variant"]
    _fail(f"unknown builtin {name!r}")
    raise AssertionError("unreachable")


def render_python(table: dict) -> str:
    out = [
        '"""Builtin exception kind codes (`BuiltinExc` discriminants) and spellings.\n\n',
        "@generated by tools/gen_exception_kinds.py from runtime/exception_kinds.toml.\n",
        'Do not edit. The runtime decodes these codes with `ExcKind::from_code`.\n"""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import Final\n\n",
        "BUILTIN_EXCEPTION_CODES: Final[dict[str, int]] = {\n",
    ]
    for index, row in enumerate(table["builtin"]):
        if row["name_lookup"]:
            out.append(f'    "{row["name"]}": {index + 1},\n')
    out.append("}\n\n")
    names = sorted(
        {row["name"] for row in table["builtin"] if row["builtin_binding"]}
        | {row["name"] for row in table["alias"]}
    )
    out.append(
        "# Every spelling some target binds in builtins (version and platform\n"
        "# gating stays with the runtime schema rows).\n"
        "BUILTIN_EXCEPTION_NAMES: Final[frozenset[str]] = frozenset(\n    {\n"
    )
    for name in names:
        out.append(f'        "{name}",\n')
    out.append("    }\n)\n")
    return "".join(out)


def render_all(table: dict) -> dict[Path, str]:
    rendered = rustfmt_sources(
        {OUT_MODEL: render_model(table)}, label="exception kinds"
    )
    rendered[OUT_PYTHON] = render_python(table)
    return rendered


def generated_outputs() -> dict[Path, str]:
    """Each output path mapped to its exact generated text."""
    return render_all(load_table())


def main(argv: list[str] | None = None) -> int:
    return generator_main(generated_outputs, argv, description=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
