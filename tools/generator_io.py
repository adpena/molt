"""The generator contract: one command line and one publication path.

Every generator in ``tools/generator_manifest.toml`` defines
``generated_outputs() -> {output path: exact text}`` and a one-line ``main``
that hands it to :func:`generator_main`. Checking and writing are the same
mapping compared or published, so no generator re-implements either, and
``tools/generators.py`` can render every generator in one interpreter.
"""

from __future__ import annotations

import argparse
import functools
import hashlib
import os
import sys
import tempfile
from collections.abc import Callable, Hashable, Mapping, Sequence
from pathlib import Path
from typing import TypeVar

ROOT = Path(__file__).resolve().parents[1]

GeneratedOutputs = Mapping[Path, str]
Render = Callable[[], GeneratedOutputs]
_Key = TypeVar("_Key", bound=Hashable)

# One rustfmt run takes this many argument characters at most; Windows limits
# a command line to 32,767.
_RUSTFMT_ARGV_CHAR_BUDGET = 16_000
_RUSTFMT_CACHE_SCHEMA = "molt.generator-rustfmt.v1"


def canonical_generated_bytes(payload: bytes) -> bytes:
    """Return the repository-canonical LF representation of generated bytes."""

    return payload.replace(b"\r\n", b"\n").replace(b"\r", b"\n")


def generated_file_matches(path: Path, expected: bytes | str) -> bool:
    """Compare generated content independently of checkout newline policy."""

    try:
        current = path.read_bytes()
    except FileNotFoundError:
        return False
    expected_bytes = expected.encode("utf-8") if isinstance(expected, str) else expected
    return canonical_generated_bytes(current) == canonical_generated_bytes(
        expected_bytes
    )


def write_generated_text(path: Path, text: str) -> None:
    """Publish generated UTF-8 text with the repository-canonical LF encoding."""

    from molt.file_publication import atomic_write_bytes

    atomic_write_bytes(path, canonical_generated_bytes(text.encode("utf-8")))


def write_generated_texts(outputs: Mapping[Path, str]) -> tuple[Path, ...]:
    """Publish one complete generated family through the artifact transaction.

    Returned journals retain custody of any cleanup residue after commit.
    """
    from molt.artifact_publication import (
        discard_staged_output,
        publish_validated_outputs,
        staged_output_path,
    )

    pairs: list[tuple[Path, Path]] = []
    try:
        for final, text in outputs.items():
            staged = staged_output_path(final)
            pairs.append((staged, final))
            with staged.open("xb") as stream:
                stream.write(canonical_generated_bytes(text.encode("utf-8")))
        return publish_validated_outputs(pairs)
    finally:
        for staged, _final in pairs:
            discard_staged_output(staged)


def stale_outputs(outputs: GeneratedOutputs) -> list[Path]:
    """Outputs whose committed bytes differ from the rendered text."""

    return [
        path for path, text in outputs.items() if not generated_file_matches(path, text)
    ]


def write_outputs(outputs: GeneratedOutputs) -> list[Path]:
    """Publish every stale output; returns the paths that changed."""

    changed = stale_outputs(outputs)
    if changed:
        write_generated_texts({path: outputs[path] for path in changed})
    return changed


def rustfmt_command() -> tuple[str, ...]:
    """The one rustfmt invocation for generated Rust.

    It formats with the workspace's edition and style, and only the file it
    names: a generated file's ``mod`` declarations name siblings the generator
    writes separately.
    """
    from molt.cargo_workspace import workspace_edition

    return (
        "rustfmt",
        "--edition",
        workspace_edition(ROOT),
        "--config",
        "skip_children=true",
    )


@functools.cache
def rustfmt_version() -> str:
    """The selected rustfmt's version, which keys every formatted output."""
    result = _guarded_rustfmt(["rustfmt", "--version"], label="the generator cache")
    return result.strip()


def rustfmt_source(source: str, *, label: str) -> str:
    """Format one generated Rust source; ``label`` names it in errors."""
    return rustfmt_sources({label: source}, label=label)[label]


def rustfmt_sources(sources: Mapping[_Key, str], *, label: str) -> dict[_Key, str]:
    """Format generated Rust sources the one way every generator does.

    A source rustfmt already formatted, under the same version and command,
    comes from a content-addressed cache outside the checkout. The others
    format alone, each in its own scratch directory outside the checkout, in
    as few rustfmt runs as the command-line budget allows, under the
    generator memory guard.
    """
    if not sources:
        return {}
    command = rustfmt_command()
    version = rustfmt_version()
    formatted: dict[_Key, str] = {}
    misses: dict[_Key, str] = {}
    for key, source in sources.items():
        cached = _rustfmt_cache_read(command, version, source)
        if cached is None:
            misses[key] = source
        else:
            formatted[key] = cached
    if misses:
        with tempfile.TemporaryDirectory(prefix="molt-generator-rustfmt-") as raw:
            scratch: dict[_Key, Path] = {}
            for index, (key, source) in enumerate(misses.items()):
                path = Path(raw) / str(index) / "generated.rs"
                path.parent.mkdir()
                path.write_text(source, encoding="utf-8", newline="\n")
                scratch[key] = path
            for batch in _argv_batches(list(scratch.values())):
                _guarded_rustfmt([*command, *map(str, batch)], label=label)
            for key, path in scratch.items():
                text = path.read_text(encoding="utf-8")
                formatted[key] = text
                _rustfmt_cache_write(command, version, misses[key], text)
    return {key: formatted[key] for key in sources}


def _guarded_rustfmt(command: Sequence[str], *, label: str) -> str:
    from tools import harness_memory_guard  # type: ignore[no-redef]

    try:
        result = harness_memory_guard.guarded_completed_process(
            list(command),
            prefix="MOLT_GENERATOR",
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=120.0,
            errors="strict",
        )
    except FileNotFoundError as exc:
        raise RuntimeError(f"rustfmt is required to generate {label}") from exc
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip()
        raise RuntimeError(f"rustfmt failed for {label}:\n{detail}")
    if not isinstance(result.stdout, str):
        raise TypeError("rustfmt stdout must be text when text=True")
    return result.stdout


def _argv_batches(paths: Sequence[Path]) -> list[list[Path]]:
    batches: list[list[Path]] = []
    batch: list[Path] = []
    used = 0
    for path in paths:
        cost = len(str(path)) + 3
        if batch and used + cost > _RUSTFMT_ARGV_CHAR_BUDGET:
            batches.append(batch)
            batch, used = [], 0
        batch.append(path)
        used += cost
    if batch:
        batches.append(batch)
    return batches


def _rustfmt_cache_path(command: Sequence[str], version: str, source: str) -> Path:
    from molt.dx import scratch_dir

    digest = hashlib.sha256()
    for part in (_RUSTFMT_CACHE_SCHEMA, version, *command):
        digest.update(part.encode() + b"\0")
    digest.update(source.encode())
    return scratch_dir(ROOT, "generator_rustfmt") / f"{digest.hexdigest()}.rs"


def _rustfmt_cache_read(
    command: Sequence[str], version: str, source: str
) -> str | None:
    try:
        return _rustfmt_cache_path(command, version, source).read_text(encoding="utf-8")
    except OSError:
        return None


def _rustfmt_cache_write(
    command: Sequence[str], version: str, source: str, formatted: str
) -> None:
    path = _rustfmt_cache_path(command, version, source)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(formatted, encoding="utf-8", newline="\n")
    temporary.replace(path)


def ruff_format_source(source: str, *, path: Path) -> str:
    """Format generated Python the one way every generator does.

    The repository ruff formats the source on stdin as if it were ``path``,
    so the project configuration and its per-path rules apply, under the
    generator memory guard. It keeps no cache, so it never writes into the
    checkout.
    """
    from tools import harness_memory_guard  # type: ignore[no-redef]

    result = harness_memory_guard.guarded_completed_process(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--no-cache",
            "--no-force-exclude",
            "--stdin-filename",
            str(path),
            "-",
        ],
        prefix="MOLT_GENERATOR",
        cwd=ROOT,
        input=source,
        capture_output=True,
        text=True,
        timeout=60.0,
        errors="strict",
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip()
        raise RuntimeError(f"ruff format failed for {display_path(path)}:\n{detail}")
    if not isinstance(result.stdout, str):
        raise TypeError("ruff stdout must be text when text=True")
    return result.stdout


def display_path(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def generator_main(
    render: Render,
    argv: Sequence[str] | None = None,
    *,
    description: str | None = None,
) -> int:
    """The one generator command line: exactly one of ``--check`` or ``--write``.

    ``--check`` exits 1 and names each stale output on stderr; ``--write``
    publishes stale outputs and leaves current ones untouched.
    """

    parser = argparse.ArgumentParser(
        description=description, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--check", action="store_true", help="exit 1 if any output is stale"
    )
    mode.add_argument("--write", action="store_true", help="rewrite stale outputs")
    args = parser.parse_args(argv)
    outputs = render()
    if args.check:
        stale = stale_outputs(outputs)
        for path in stale:
            print(f"stale: {display_path(path)}", file=sys.stderr)
        if stale:
            print("regenerate with --write", file=sys.stderr)
            return 1
        print(f"{len(outputs)} generated output(s) current")
        return 0
    for path in write_outputs(outputs):
        print(f"wrote {display_path(path)}")
    return 0
