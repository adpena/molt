#!/usr/bin/env python3
"""Generated merge attributes and the shared post-source-merge resolver.

Workers run ``python tools/generated_merge.py merge origin/main``. The landing
queue calls ``resolve_generated_merge`` only after Git reports a failed merge.
Git's built-in binary driver needs neither hooks nor local driver configuration.
"""

from __future__ import annotations

import argparse
from collections.abc import Callable, Sequence
from dataclasses import dataclass
import json
import os
from pathlib import Path, PurePosixPath
import sys
import tempfile
import tomllib
from typing import Protocol

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))
from tools.import_file import bind_repository_imports  # noqa: E402

bind_repository_imports(__file__)

from tools.command_execution import CommandExecutor  # noqa: E402
from tools.generator_io import generator_main, merge_eligible  # noqa: E402

ROOT = _REPO_ROOT
_COMMANDS = CommandExecutor.for_file(__file__, stem="MOLT_DEV")

# The source for the non-generator attributes; .gitattributes is fully generated
# so resolving a conflict there cannot discard hand-authored source changes.
BASE_ATTRIBUTES = """# One checkout representation for every text authority.
* text=auto eol=lf

# Preserve complete upstream licenses and their original whitespace.
vendor/rust/cranelift-object/LICENSE whitespace=-blank-at-eof
vendor/rust/zlib-rs/LICENSE whitespace=-blank-at-eof,-blank-at-eol

# Native Windows command scripts require CRLF.
*.bat text eol=crlf
*.cmd text eol=crlf

# Published compression corpora are byte inputs.
vendor/rust/zlib-rs/src/deflate/test-data/* binary

# Findings rows merge by ID through the existing managed ledger driver.
docs/agent/V1_HANDOFF_FINDINGS.md merge=molt-ledger
"""


class GeneratedMergeError(RuntimeError):
    """The merge remains uncommitted; its original error is retained."""


@dataclass(frozen=True)
class OutputOwner:
    tool: str
    eligible: bool
    reason: str


def output_owners(root: Path) -> dict[str, OutputOwner]:
    with (root / "tools/generator_manifest.toml").open("rb") as stream:
        rows = tomllib.load(stream)["generator"]
    owners: dict[str, OutputOwner] = {}
    for row in rows:
        eligible = merge_eligible(row)
        reason = row.get("ci_skip_reason") or "generator is not idempotent"
        for path in row["outputs"]:
            relative = PurePosixPath(path)
            if relative.is_absolute() or ".." in relative.parts or not relative.parts:
                raise GeneratedMergeError(f"invalid generated output path: {path!r}")
            if path in owners:
                raise GeneratedMergeError(f"multiple generators own {path}")
            owners[path] = OutputOwner(row["tool"], bool(eligible), str(reason))
    return owners


def generated_outputs() -> dict[Path, str]:
    lines = [
        "# @generated by tools/generated_merge.py; do not edit.\n",
        "# Source: tools/generator_manifest.toml and BASE_ATTRIBUTES in the generator.\n",
        BASE_ATTRIBUTES,
        "\n# Eligible generated projections are regenerated after sources merge.\n",
    ]
    for path, owner in sorted(output_owners(ROOT).items()):
        if owner.eligible:
            # An anchored, C-quoted attribute pattern is an exact repository path.
            # Escape wildcard syntax too; manifest outputs are filenames, not globs.
            pattern = "/" + "".join("\\" + c if c in "*?[\\" else c for c in path)
            lines.append(f"{json.dumps(pattern, ensure_ascii=False)} merge=binary\n")
    return {ROOT / ".gitattributes": "".join(lines)}


class GitResult(Protocol):
    returncode: int
    stdout: str
    stderr: str


GitRunner = Callable[[Sequence[str]], GitResult]


def _git(run_git: GitRunner, *args: str) -> GitResult:
    result = run_git(args)
    if result.returncode:
        raise GeneratedMergeError(
            f"git {' '.join(args)}: {result.stderr.strip() or result.stdout.strip()}"
        )
    return result


def regenerate(root: Path, tools: tuple[str, ...]) -> tuple[str, ...]:
    """Use the checkout's selected image, as its generator check gate does."""
    from tools.venv_exec import VenvExecError, resolve_venv, venv_env, venv_python
    from molt import checkout_provisioning

    if os.environ.get("UV_PROJECT_ENVIRONMENT") or os.environ.get("MOLT_VENV"):
        try:
            image = resolve_venv(repo_root=root)
        except VenvExecError as exc:
            raise GeneratedMergeError(str(exc)) from exc
    else:
        try:
            prepared = checkout_provisioning.ensure(
                "uv-environment", root, guard_source_root=_COMMANDS.repo_root
            )
        except checkout_provisioning.ProvisioningError as exc:
            raise GeneratedMergeError(str(exc)) from exc
        if prepared.environment_root is None:
            raise GeneratedMergeError("merge has no selected development image")
        image = prepared.environment_root
    environment = venv_env(venv=image, managed=True)
    # A shared editable image must import this merged checkout, not its donor.
    environment = environment.updated(
        {"PYTHONPATH": os.pathsep.join((str(root / "src"), str(root)))}
    )
    try:
        selected_python = venv_python(image)
    except VenvExecError as exc:
        raise GeneratedMergeError(str(exc)) from exc
    with tempfile.TemporaryDirectory(prefix="molt-generated-merge-") as raw:
        receipt = Path(raw) / "outputs.json"
        command = [
            str(selected_python),
            "-B",
            str(root / "tools/generators.py"),
            "merge",
            "--output-list",
            str(receipt),
        ]
        for tool in tools:
            command.extend(("--only", tool))
        result = _COMMANDS.run(
            command,
            cwd=root,
            env=environment,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        if result.stdout:
            print(result.stdout, end="", flush=True)
        if result.returncode:
            raise GeneratedMergeError(result.stderr.strip() or result.stdout.strip())
        paths = json.loads(receipt.read_text(encoding="utf-8"))
        if not isinstance(paths, list) or not all(isinstance(p, str) for p in paths):
            raise GeneratedMergeError("invalid generated merge output receipt")
        for path in paths:
            if PurePosixPath(path).is_absolute() or ".." in PurePosixPath(path).parts:
                raise GeneratedMergeError(f"generator output escapes checkout: {path}")
        return tuple(paths)


def resolve_generated_merge(run_git: GitRunner) -> bool:
    """Resolve only an all-generated conflict set, then create the merge commit.

    The caller invokes this only after a failed merge. Source conflicts return
    False without writes; generator failures raise and leave the merge pending.
    """
    pending = _git(run_git, "diff", "--name-only", "--diff-filter=U", "-z").stdout
    paths = tuple(p for p in pending.split("\0") if p)
    if not paths:
        return False
    root = Path(_git(run_git, "rev-parse", "--show-toplevel").stdout.strip())
    # Do not parse an unmerged manifest (or any source) to authorize a repair.
    if "tools/generator_manifest.toml" in paths:
        return False
    owners = output_owners(root)
    if any(path not in owners for path in paths):
        return False
    excluded = [path for path in paths if not owners[path].eligible]
    if excluded:
        raise GeneratedMergeError(
            "\n".join(
                f"{path}: {owners[path].tool}: {owners[path].reason}; resolve as text"
                for path in excluded
            )
        )
    # An uncommitted source edit must never become a committed projection.
    dirty = _git(run_git, "diff", "--name-only", "-z").stdout.split("\0")
    if any(path and path not in paths for path in dirty):
        raise GeneratedMergeError(
            "unstaged changes outside generated conflicts; merge left pending"
        )
    _git(run_git, "rev-parse", "--verify", "MERGE_HEAD")
    tools = tuple(sorted({owners[path].tool for path in paths}))
    outputs = regenerate(root, tools)
    if not set(paths).issubset(outputs):
        raise GeneratedMergeError(
            "generator no longer produces every conflicted output"
        )
    # Literal, NUL-framed pathspecs preserve unusual filenames and stay below
    # Windows' command-line limit even for large generated families.
    with tempfile.TemporaryDirectory(prefix="molt-generated-stage-") as raw:
        pathspec = Path(raw) / "paths"
        pathspec.write_bytes(b"\0".join(os.fsencode(path) for path in outputs) + b"\0")
        _git(
            run_git,
            "--literal-pathspecs",
            "add",
            f"--pathspec-from-file={pathspec}",
            "--pathspec-file-nul",
        )
    _git(run_git, "commit", "--no-edit")
    return True


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments and arguments[0] in ("--check", "--write"):
        return generator_main(generated_outputs, arguments, description=__doc__)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("merge",))
    parser.add_argument("ref")
    args = parser.parse_args(arguments)

    def run_git(command: Sequence[str]) -> GitResult:
        return _COMMANDS.run(
            ["git", *command],
            cwd=ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )

    result = run_git(("merge", "--no-edit", "--", args.ref))
    print(result.stdout, end="", flush=True)
    if result.returncode == 0:
        return 0
    try:
        if resolve_generated_merge(run_git):
            print("Generated projections verified; merge committed.")
            return 0
    except (GeneratedMergeError, OSError, ValueError) as exc:
        print(f"generated merge: {exc}", file=sys.stderr)
        return 1
    print(result.stderr, end="", file=sys.stderr)
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
