def _format_tuple(items: tuple[str, ...], *, indent: int) -> str:
    spaces = " " * indent
    lines = ["("]
    for item in items:
        lines.append(f'{spaces}"{item}",')
    lines.append(" " * (indent - 4) + ")")
    return "\n".join(lines)


def _version_module_stem(output: Path, version: str) -> str:
    safe = "".join(ch if ch.isalnum() else "_" for ch in version)
    return f"{output.stem}_{safe}"


def _format_version_module(*, version: str, data: VersionData) -> str:
    return "\n".join(
        [
            '"""',
            GENERATED_DATA_MARKER,
            "",
            f"Python baseline: {version}",
            f"CPython source: {data.tag} ({data.revision})",
            "",
            "Generated by tools/gen_stdlib_module_union.py.",
            '"""',
            "",
            f"PYTHON_VERSION = {json.dumps(version)}",
            "",
            f"STDLIB_MODULES = {_format_tuple(data.modules, indent=4)}",
            "",
            f"STDLIB_PACKAGES = {_format_tuple(data.packages, indent=4)}",
            "",
            f"STDLIB_PY_MODULES = {_format_tuple(data.py_modules, indent=4)}",
            "",
            f"STDLIB_PY_PACKAGES = {_format_tuple(data.py_packages, indent=4)}",
            "",
        ]
    )


def _format_facade_module(
    *,
    output: Path,
    versions: tuple[str, ...],
    union_modules: tuple[str, ...],
    union_packages: tuple[str, ...],
    union_py_modules: tuple[str, ...],
    union_py_packages: tuple[str, ...],
    union_py_submodules: tuple[str, ...],
    union_py_subpackages: tuple[str, ...],
) -> str:
    module_stems = {
        version: _version_module_stem(output, version) for version in versions
    }
    # A one-element tuple needs its trailing comma.
    version_items = ", ".join(json.dumps(version) for version in versions)
    version_tuple = f"({version_items}{',' if len(versions) == 1 else ''})"
    return "\n".join(
        [
            '"""',
            "Autogenerated CPython stdlib top-level union baseline.",
            "",
            "Update workflow:",
            "1. Pin each CPython tag and revision in config/cpython_regrtest_sources.toml.",
            "2. Run `python3 tools/gen_stdlib_module_union.py --refresh-sources`.",
            "3. Run `python3 tools/gen_stdlib_module_union.py --write`.",
            "4. Run `python3 tools/gen_stdlib_stubs.py --write`.",
            "5. Re-run `python3 tools/check_stdlib_intrinsics.py --update-doc`.",
            "",
            "This file is consumed by tools/check_stdlib_intrinsics.py and is the",
            "hard gate baseline for top-level + submodule stdlib coverage.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "import runpy as _runpy",
            "from pathlib import Path as _Path",
            "",
            f"BASELINE_PYTHON_VERSIONS = {version_tuple}",
            "",
            "_VERSION_MODULE_STEMS = {",
            *(
                f"    {json.dumps(version)}: {json.dumps(stem)},"
                for version, stem in module_stems.items()
            ),
            "}",
            "",
            "",
            "def _load_version_data(version: str) -> dict[str, object]:",
            "    # Sibling data files, read as data: no second module identity.",
            "    stem = _VERSION_MODULE_STEMS[version]",
            '    return _runpy.run_path(str(_Path(__file__).with_name(f"{stem}.py")))',
            "",
            "",
            "_VERSION_DATA = {",
            "    version: _load_version_data(version) for version in BASELINE_PYTHON_VERSIONS",
            "}",
            "",
            "STDLIB_MODULES_BY_VERSION = {",
            '    version: _VERSION_DATA[version]["STDLIB_MODULES"]',
            "    for version in BASELINE_PYTHON_VERSIONS",
            "}",
            "STDLIB_PACKAGES_BY_VERSION = {",
            '    version: _VERSION_DATA[version]["STDLIB_PACKAGES"]',
            "    for version in BASELINE_PYTHON_VERSIONS",
            "}",
            "STDLIB_PY_MODULES_BY_VERSION = {",
            '    version: _VERSION_DATA[version]["STDLIB_PY_MODULES"]',
            "    for version in BASELINE_PYTHON_VERSIONS",
            "}",
            "STDLIB_PY_PACKAGES_BY_VERSION = {",
            '    version: _VERSION_DATA[version]["STDLIB_PY_PACKAGES"]',
            "    for version in BASELINE_PYTHON_VERSIONS",
            "}",
            "",
            f"STDLIB_MODULE_UNION = {_format_tuple(union_modules, indent=4)}",
            "",
            f"STDLIB_PACKAGE_UNION = {_format_tuple(union_packages, indent=4)}",
            "",
            f"STDLIB_PY_MODULE_UNION = {_format_tuple(union_py_modules, indent=4)}",
            "",
            f"STDLIB_PY_PACKAGE_UNION = {_format_tuple(union_py_packages, indent=4)}",
            "",
            f"STDLIB_PY_SUBMODULE_UNION = {_format_tuple(union_py_submodules, indent=4)}",
            "",
            f"STDLIB_PY_SUBPACKAGE_UNION = {_format_tuple(union_py_subpackages, indent=4)}",
            "",
        ]
    )


def render_outputs(
    *,
    output: Path,
    versions: tuple[str, ...],
    data: Mapping[str, VersionData],
) -> dict[Path, str]:
    def union(field: Callable[[VersionData], tuple[str, ...]]) -> tuple[str, ...]:
        return tuple(
            sorted({name for version in versions for name in field(data[version])})
        )

    union_py_modules = union(lambda d: d.py_modules)
    union_py_packages = union(lambda d: d.py_packages)
    rendered: dict[Path, str] = {}
    for version in versions:
        path = output.with_name(f"{_version_module_stem(output, version)}.py")
        rendered[path] = _format_version_module(version=version, data=data[version])
    rendered[output] = _format_facade_module(
        output=output,
        versions=versions,
        union_modules=union(lambda d: d.modules),
        union_packages=union(lambda d: d.packages),
        union_py_modules=union_py_modules,
        union_py_packages=union_py_packages,
        union_py_submodules=tuple(name for name in union_py_modules if "." in name),
        union_py_subpackages=tuple(name for name in union_py_packages if "." in name),
    )
    return rendered


def _stale_generated_siblings(output: Path, expected: set[Path]) -> list[Path]:
    """Per-version data modules of a version no longer in the baseline."""
    stale: list[Path] = []
    for path in sorted(output.parent.glob(f"{output.stem}_*.py")):
        if path in expected:
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        if GENERATED_DATA_MARKER in text:
            stale.append(path)
    return stale


def generated_outputs() -> dict[Path, str]:
    """Each output path mapped to its exact generated text.

    A per-version data module for a version that left the baseline is part of
    the authority: rendering raises while one exists (before any source is
    read), so ``--check`` and ``--write`` both fail closed naming it.
    """
    versions = tuple(dict.fromkeys(DEFAULT_PYTHONS))
    expected = {OUT_PATH} | {
        OUT_PATH.with_name(f"{_version_module_stem(OUT_PATH, version)}.py")
        for version in versions
    }
    stale = _stale_generated_siblings(OUT_PATH, expected)
    if stale:
        raise RuntimeError(
            "delete generated files that tools/gen_stdlib_module_union.py no "
            "longer renders: " + ", ".join(display_path(path) for path in stale)
        )
    snapshots = pinned_snapshots(versions)
    return render_outputs(
        output=OUT_PATH,
        versions=versions,
        data={version: version_data(snapshots[version]) for version in versions},
    )


def _source_change_detail(before: str, after: str) -> dict[str, object] | None:
    """One linear changed span, not an inferred minimal/semantic edit script.

    Offsets and lengths count Unicode code points. Each side emits at most
    2048 code points even for one enormous line; complete text stays in the
    hash-bound snapshot. Prefix/suffix never overlap an insertion/deletion.
    """
    if before == after:
        return None
    shared = min(len(before), len(after))
    prefix = 0
    while prefix < shared and before[prefix] == after[prefix]:
        prefix += 1
    suffix = 0
    while suffix < shared - prefix and before[-suffix - 1] == after[-suffix - 1]:
        suffix += 1

    def interval(text: str) -> dict[str, object]:
        end = len(text) - suffix
        length = end - prefix
        head_length = min(length, 1024)
        tail_length = min(length - head_length, 1024)
        return {
            "start_char": prefix,
            "end_char": end,
            "total_chars": len(text),
            "changed_chars": length,
            "head": text[prefix : prefix + head_length],
            "tail": text[end - tail_length : end] if tail_length else "",
            "omitted_chars": length - head_length - tail_length,
        }

    return {
        "common_prefix_chars": prefix,
        "common_suffix_chars": suffix,
        "before": interval(before),
        "after": interval(after),
    }


@dataclass(frozen=True)
class ModuleAssessment:
    module: str
    change: Literal["added", "removed", "changed"]
    upstream_kind: Literal["package", "module"]
    upstream_source: Literal["python", "native-or-builtin", "namespace"]
    current_status: str | None
    current_path: str | None
    current_kind: Literal["package", "module"] | None
    current_sha256: str | None
    status_assessed: bool
    missing: bool
    kind_matches: bool | None
    retention: Literal["retain-for-owning-version-review"] | None
    owner: str = "UNKNOWN"
    witness: str = "UNKNOWN"
    execution_evidence: Literal["UNKNOWN"] = "UNKNOWN"


@dataclass(frozen=True)
class NumericAssessment:
    context: str
    operation: str
    operand_kind: str
    error_class: str
    candidate: str
    declared_observation: bool
    message: str | None
    owner: str = "tools/gen_python_numeric_errors.py"
    witness: str = "UNKNOWN"
    execution_evidence: Literal["UNKNOWN"] = "UNKNOWN"


def _prerequisite_assessment(
    before: VersionData, after: VersionData, *, base: str, candidate: str
) -> dict[str, object]:
    """Join existing implementation/declaration facts, never infer parity."""
    from tools import check_stdlib_intrinsics as stdlib
    from tools import gen_python_numeric_errors as numeric
    from molt.compiler_analysis.python_syntax import PYTHON_SYNTAX_DELTAS
    from molt.target_python import _DEFAULT_TARGET_PYTHON_VERSION

    syntax_owner = ROOT / "src/molt/compiler_analysis/python_syntax.py"

    def namespace_paths() -> tuple[Path, ...]:
        return tuple(
            path
            for path in sorted(stdlib.STDLIB_ROOT.rglob("*.py"))
            if not path.name.startswith(".")
        )

    left = set(before.modules) | set(before.py_modules)
    right = set(after.modules) | set(after.py_modules)

    def membership(name: str, data: VersionData) -> tuple[bool, ...]:
        return tuple(
            name in getattr(data, field)
            for field in ("modules", "packages", "py_modules", "py_packages")
        )

    changes = (
        ("added", right - left, after),
        ("removed", left - right, before),
        (
            "changed",
            {
                name
                for name in left & right
                if membership(name, before) != membership(name, after)
            },
            after,
        ),
    )
    namespace = namespace_paths()
    current_paths = {stdlib._module_name(path): path for path in namespace}
    needs_status = any(
        names & current_paths.keys()
        for change, names, _ in changes
        if change != "removed"
    )
    removed_paths = tuple(
        current_paths[name] for name in sorted(left - right) if name in current_paths
    )
    # Absence needs only namespace membership; removed names need physical
    # retention facts. Added/changed status needs the full namespace, once.
    paths = (
        (*namespace, stdlib.STDLIB_FULL_COVERAGE_MANIFEST, numeric.SOURCE)
        if needs_status
        else (*removed_paths, numeric.SOURCE)
    )
    identities = {
        path: capture_stable_regular_file(path, label="source assessment input")[0]
        for path in paths
    }
    statuses = stdlib.stdlib_module_statuses() if needs_status else {}
    contexts = numeric.load_policy(numeric.SOURCE)
    if namespace_paths() != namespace:
        raise RuntimeError("current stdlib membership changed during source assessment")
    rows = []
    for change, names, upstream in changes:
        for name in sorted(names):
            package = name in upstream.packages or name in upstream.py_packages
            source = (
                "python"
                if name in upstream.py_modules
                else "namespace"
                if package
                else "native-or-builtin"
            )
            path = current_paths.get(name)
            assessed = change != "removed" and path is not None
            status = statuses[name][0] if assessed else "UNKNOWN" if path else None
            current_kind = (
                ("package" if path.name == "__init__.py" else "module")
                if path
                else None
            )
            expected_kind = "package" if package else "module"
            rows.append(
                ModuleAssessment(
                    module=name,
                    change=change,
                    upstream_kind=expected_kind,
                    upstream_source=source,
                    current_status=status,
                    current_path=stdlib._display_path(path) if path else None,
                    current_kind=current_kind,
                    current_sha256=identities[path].sha256 if path else None,
                    status_assessed=assessed,
                    missing=path is None,
                    kind_matches=current_kind == expected_kind if path else None,
                    retention="retain-for-owning-version-review"
                    if change == "removed"
                    else None,
                )
            )
    numeric_rows = [
        NumericAssessment(
            context=context.name,
            operation=context.operation,
            operand_kind=context.operand_kind,
            error_class=context.error_class,
            candidate=candidate,
            declared_observation=candidate in context.messages,
            message=context.messages.get(candidate),
        )
        for context in contexts
    ]
    syntax_rows = [
        {
            "family": delta.family.value,
            "minimum_version": ".".join(map(str, delta.minimum_version)),
            "introduced_in_delta": (
                _version_key(base) < delta.minimum_version <= _version_key(candidate)
            ),
            "pep_url": delta.pep_url,
            "admission_disposition": delta.disposition,
            "owner": stdlib._display_path(syntax_owner),
            "witness_paths": list(delta.witness_paths),
            "execution_evidence": "UNKNOWN",
        }
        for delta in PYTHON_SYNTAX_DELTAS
    ]
    for identity in identities.values():
        verify_stable_regular_file_identity(
            identity, label="source assessment input", hash_content=True
        )
    source_rows = [
        {"path": stdlib._display_path(path), "sha256": identity.sha256}
        for path, identity in identities.items()
    ]
    return {
        "analysis_target": _DEFAULT_TARGET_PYTHON_VERSION.short,
        "current_namespace_sha256": _sha256(
            json.dumps([stdlib._display_path(path) for path in namespace]).encode(
                "utf-8"
            )
        ),
        "status_analysis_used": needs_status,
        "current_source_inputs": source_rows,
        "modules": [asdict(row) for row in rows],
        "numeric_contexts": [asdict(row) for row in numeric_rows],
        "syntax_families": syntax_rows,
        "syntax_metadata_sha256": _sha256(
            json.dumps(syntax_rows, sort_keys=True, separators=(",", ":")).encode(
                "utf-8"
            )
        ),
        "syntax_source_binding": "loaded-canonical-metadata; owner-path-is-a-review-pointer",
        "syntax_inventory_scope": "known-tracked-families-only",
        "interpretation": (
            "Current-source status and declared observations are prerequisites, "
            "not candidate-target execution or full-coverage attestations. "
            "UNKNOWN owner, witness and execution evidence require owning review."
        ),
    }


def source_comparison(base: str, candidate: str) -> dict[str, object]:
    """Compare pinned source facts without admitting or qualifying a target."""
    pins_identity, _ = capture_stable_regular_file(
        PINS_PATH, label="CPython source pins"
    )
    snapshot_identity, _ = capture_stable_regular_file(
        SNAPSHOT_PATH, label="CPython source snapshot"
    )
    snapshots = pinned_snapshots((base, candidate))
    if (
        capture_stable_regular_file(PINS_PATH, label="CPython source pins")[0]
        != pins_identity
        or capture_stable_regular_file(SNAPSHOT_PATH, label="CPython source snapshot")[
            0
        ]
        != snapshot_identity
    ):
        raise RuntimeError("CPython source evidence changed during comparison")
    before, after = snapshots[base], snapshots[candidate]
    policy, reference_identity = capture_verified_subset_policy(REFERENCE_POLICY)
    reference_by_minor = dict(zip(policy.python_versions, policy.reference_cpython))

    def coordinate(snapshot: SourceSnapshot) -> dict[str, object]:
        reference = reference_by_minor.get(snapshot.python)
        return {
            "python": snapshot.python,
            "tag": snapshot.tag,
            "revision": snapshot.revision,
            "admitted_target": snapshot.python in DEFAULT_PYTHONS,
            "configured_reference": reference,
            "source_matches_reference_patch": reference
            == snapshot.tag.removeprefix("v"),
            "qualification": "requires-source-bound-execution-receipts",
        }

    left, right = version_data(before), version_data(after)
    membership = {}
    for field in ("modules", "packages", "py_modules", "py_packages"):
        a, b = set(getattr(left, field)), set(getattr(right, field))
        membership[field] = {"added": sorted(b - a), "removed": sorted(a - b)}
    evidence = []
    for a, b in zip(before.inputs, after.inputs):
        if a.role != b.role:
            raise ValueError("source evidence roles disagree")
        evidence.append(
            {
                "role": a.role,
                "before": {
                    "path": a.path,
                    "git_object": a.git_object,
                    "sha256": a.sha256(),
                },
                "after": {
                    "path": b.path,
                    "git_object": b.git_object,
                    "sha256": b.sha256(),
                },
                "changed": a.text != b.text,
                "changed_interval": _source_change_detail(a.text, b.text),
            }
        )
    assessment = _prerequisite_assessment(left, right, base=base, candidate=candidate)
    for identity in (pins_identity, snapshot_identity, reference_identity):
        verify_stable_regular_file_identity(
            identity, label="CPython comparison authority", hash_content=True
        )
    return {
        "schema": "molt.cpython-source-comparison.v1",
        "custody": {
            "pins_sha256": pins_identity.sha256,
            "snapshot_sha256": snapshot_identity.sha256,
            "reference_policy_sha256": reference_identity.sha256,
            "admitted_catalog": list(DEFAULT_PYTHONS),
        },
        "before": coordinate(before),
        "after": coordinate(after),
        "stdlib_membership": membership,
        "source_inputs": evidence,
        "prerequisites": assessment,
        "interpretation": "Source changes require owning-contract review; unchanged bytes are not behavioral qualification.",
    }


def main(argv: list[str] | None = None) -> int:
    # Refreshing the pinned inputs is this generator's own mode; checking and
    # writing the outputs stay with the shared generator command line.
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--refresh-sources", action="store_true")
    parser.add_argument("--compare-sources", nargs=2, metavar=("BASE", "CANDIDATE"))
    parser.add_argument("--report", type=Path)
    refresh, rest = parser.parse_known_args(argv)
    if refresh.compare_sources:
        if refresh.refresh_sources or rest or refresh.report is None:
            parser.error(
                "--compare-sources requires --report and takes no generator/refresh options"
            )
        report = (
            json.dumps(source_comparison(*refresh.compare_sources), indent=2) + "\n"
        )
        write_generated_text(refresh.report, report)
        return 0
    if refresh.report is not None:
        parser.error("--report requires --compare-sources")
    if refresh.refresh_sources:
        if rest:
            parser.error("--refresh-sources takes no other option")
        return refresh_sources()
    return generator_main(generated_outputs, rest, description=__doc__)


