#!/usr/bin/env python3
"""
Generate the versioned CPython stdlib top-level union baseline.

This script is the single writer for `tools/stdlib_module_union.py` and its
per-version generated siblings (`tools/stdlib_module_union_*.py`). It derives
the data for each supported version from the CPython source revision pinned in
`config/cpython_regrtest_sources.toml`, never from a host interpreter, whose
build may drop or add files:

1. module names: `Python/stdlib_module_names.h`, the list CPython compiles
   into `sys.stdlib_module_names`;
2. packages: the module names that are directories under `Lib/`, which is
   where `importlib.util.find_spec(name).submodule_search_locations` points on
   an unmodified install;
3. `.py` modules and packages: every `.py` file under `Lib/` whose top-level
   name is a module name; an `__init__.py` names its package.

`config/cpython_stdlib_snapshot.json` holds those inputs with a receipt per
input (tag, revision, path, git object id, sha256), so `--check` and `--write`
run offline. `--refresh-sources` fetches the pinned tags with git, requires
each tag to resolve to its pinned revision, and fails closed, writing nothing,
when the content at an unchanged revision differs from its receipt.

Pinned inputs may include a pending release; only generated module baselines select
the supported target-Python authority
(`src/molt/target_python.py`); each needs a pinned source row.

Usage::

    python3 tools/gen_stdlib_module_union.py --refresh-sources   # network
    python3 tools/gen_stdlib_module_union.py --write
    python3 tools/gen_stdlib_module_union.py --check
"""

