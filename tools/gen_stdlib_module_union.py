@dataclass(frozen=True)
class SourceInput:
    role: str
    path: str
    git_object: str
    # Blobs preserve exact UTF-8 bytes. Trees preserve sorted ls-tree records;
    # their SHA256 covers that representation, not the Git tree encoding.
    text: str

    def sha256(self) -> str:
        return _sha256(self.text.encode("utf-8"))


@dataclass(frozen=True)
class SourceSnapshot:
    """The pinned inputs of one version and their receipts.

    ``lib_entries`` lists, relative to ``Lib/``, every directory (with a
    trailing ``/``) and every ``.py`` file whose top-level name is in the
    header; nothing else under ``Lib/`` can enter the union.
    """

    python: str
    tag: str
    revision: str
    header_object: str
    header_lines: tuple[str, ...]
    lib_object: str
    lib_entries: tuple[str, ...]
    inputs: tuple[SourceInput, ...]

    def header_bytes(self) -> bytes:
        return ("\n".join(self.header_lines) + "\n").encode("utf-8")

    def lib_listing_bytes(self) -> bytes:
        return ("\n".join(self.lib_entries) + "\n").encode("utf-8")

    def receipts(self) -> dict[str, tuple[str, str]]:
        """Each input path mapped to its (git object id, sha256)."""
        return {
            HEADER_PATH: (self.header_object, _sha256(self.header_bytes())),
            LIB_PATH: (self.lib_object, _sha256(self.lib_listing_bytes())),
            **{item.path: (item.git_object, item.sha256()) for item in self.inputs},
        }


@dataclass(frozen=True)
class VersionData:
    """The union baseline of one version and the source it came from."""

    tag: str
    revision: str
    modules: tuple[str, ...]
    packages: tuple[str, ...]
    py_modules: tuple[str, ...]
    py_packages: tuple[str, ...]


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _git_blob_id(payload: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(payload) + payload).hexdigest()


def _version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


# ---------------------------------------------------------------------------
# Derivation: the semantics of `sys.stdlib_module_names`, `find_spec` and a
# walk of the installed stdlib directory, computed from the source tree.
# ---------------------------------------------------------------------------


def parse_stdlib_module_names(lines: Sequence[str]) -> tuple[str, ...]:
    """The sorted names in CPython's `_Py_stdlib_module_names` array."""
    try:
        start = list(lines).index(_HEADER_ARRAY)
    except ValueError:
        raise ValueError(f"{HEADER_PATH}: no {_HEADER_ARRAY!r} line") from None
    names: list[str] = []
    for line in lines[start + 1 :]:
        if line == "};":
            break
        match = _HEADER_NAME.fullmatch(line)
        if match is None:
            raise ValueError(f"{HEADER_PATH}: unexpected array line {line!r}")
        names.append(match.group(1))
    else:
        raise ValueError(f"{HEADER_PATH}: the module-name array is not closed")
    if not names:
        raise ValueError(f"{HEADER_PATH}: the module-name array is empty")
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise ValueError(f"{HEADER_PATH}: duplicate module names {duplicates}")
    return tuple(sorted(names))


def _top_level_name(entry: str) -> str:
    first, _, rest = entry.partition("/")
    if not rest and first.endswith(".py"):
        return first[: -len(".py")]
    return first


def derive_version_data(
    modules: Sequence[str], lib_entries: Iterable[str]
) -> tuple[tuple[str, ...], tuple[str, ...], tuple[str, ...]]:
    """(packages, py_modules, py_packages) of one stdlib tree.

    ``lib_entries`` are paths relative to the stdlib directory: a directory
    ends with ``/``. The `.py` rules match a walk of an installed stdlib
    directory exactly, including the exclusions only an install can hold
    (``__pycache__``, ``site-packages``, ``config-*``). A module name is a
    package exactly when it names a directory: CPython has no extension or
    frozen package in `sys.stdlib_module_names`, so `find_spec` reports
    `submodule_search_locations` for that directory and for nothing else.
    """
    module_set = frozenset(modules)
    directories: set[str] = set()
    py_modules: set[str] = set()
    py_packages: set[str] = set()
    for entry in lib_entries:
        if entry.endswith("/"):
            directories.add(entry[:-1])
            continue
        if not entry.endswith(".py"):
            continue
        parts = tuple(entry.split("/"))
        if "__pycache__" in parts:
            continue
        if any(part in {"site-packages", "dist-packages"} for part in parts):
            continue
        if parts[0].startswith("config-"):
            continue
        if parts[-1] == "__init__.py":
            if len(parts) == 1:
                continue
            name = ".".join(parts[:-1])
            if name.split(".", 1)[0] not in module_set:
                continue
            py_packages.add(name)
            py_modules.add(name)
        else:
            name = ".".join((*parts[:-1], parts[-1][: -len(".py")]))
            if name.split(".", 1)[0] not in module_set:
                continue
            py_modules.add(name)
    packages = tuple(name for name in sorted(module_set) if name in directories)
    return packages, tuple(sorted(py_modules)), tuple(sorted(py_packages))


def version_data(snapshot: SourceSnapshot) -> VersionData:
    modules = parse_stdlib_module_names(snapshot.header_lines)
    packages, py_modules, py_packages = derive_version_data(
        modules, snapshot.lib_entries
    )
    if not py_modules:
        raise RuntimeError(f"empty stdlib python-module list for {snapshot.python}")
    return VersionData(
        tag=snapshot.tag,
        revision=snapshot.revision,
        modules=modules,
        packages=packages,
        py_modules=py_modules,
        py_packages=py_packages,
    )


# ---------------------------------------------------------------------------
# The committed snapshot: offline inputs with receipts.
# ---------------------------------------------------------------------------


def _snapshot_row(snapshot: SourceSnapshot) -> dict[str, object]:
    receipts = snapshot.receipts()
    return {
        "python": snapshot.python,
        "tag": snapshot.tag,
        "revision": snapshot.revision,
        "header": {
            "path": HEADER_PATH,
            "git_object": receipts[HEADER_PATH][0],
            "sha256": receipts[HEADER_PATH][1],
            "lines": list(snapshot.header_lines),
        },
        "inputs": [
            {
                "role": item.role,
                "path": item.path,
                "git_object": item.git_object,
                "sha256": item.sha256(),
                "text": item.text,
            }
            for item in snapshot.inputs
        ],
        "lib": {
            "path": LIB_PATH,
            "git_object": receipts[LIB_PATH][0],
            "sha256": receipts[LIB_PATH][1],
            "entries": list(snapshot.lib_entries),
        },
    }


def render_snapshot(snapshots: Mapping[str, SourceSnapshot]) -> str:
    sources = [
        _snapshot_row(snapshots[version])
        for version in sorted(snapshots, key=_version_key)
    ]
    return json.dumps({"schema": SNAPSHOT_SCHEMA, "sources": sources}, indent=2) + "\n"


def _exact_keys(row: object, keys: set[str], where: str) -> dict[str, object]:
    if not isinstance(row, dict) or set(row) != keys:
        raise ValueError(f"{where}: expected exactly the keys {sorted(keys)}")
    return row


def _string(row: Mapping[str, object], key: str, where: str) -> str:
    value = row[key]
    if not isinstance(value, str):
        raise ValueError(f"{where}: {key} must be a string")
    return value


def _strings(row: Mapping[str, object], key: str, where: str) -> tuple[str, ...]:
    value = row[key]
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        raise ValueError(f"{where}: {key} must be a list of strings")
    return tuple(value)


def _snapshot_from_row(
    row: object, where: str, *, refresh_prior: bool = False
) -> SourceSnapshot:
    source = _exact_keys(
        row, {"python", "tag", "revision", "header", "lib", "inputs"}, where
    )
    header = _exact_keys(
        source["header"], {"path", "git_object", "sha256", "lines"}, f"{where}.header"
    )
    lib = _exact_keys(
        source["lib"], {"path", "git_object", "sha256", "entries"}, f"{where}.lib"
    )
    if header["path"] != HEADER_PATH or lib["path"] != LIB_PATH:
        raise ValueError(f"{where}: input paths must be {HEADER_PATH} and {LIB_PATH}")
    python = _string(source, "python", where)
    inputs = source["inputs"]
    if (
        not isinstance(inputs, list)
        or not inputs
        or (not refresh_prior and len(inputs) != len(EVIDENCE_PATHS))
    ):
        raise ValueError(f"{where}: complete source evidence is required")
    parsed_inputs = []
    evidence_paths = iter(EVIDENCE_PATHS)
    for item in inputs:
        item = _exact_keys(
            item, {"role", "path", "git_object", "sha256", "text"}, where
        )
        expected = next(evidence_paths, None)
        # Only refresh may read an older ordered subset. Never normalize away
        # unknown, duplicate or reordered roles, or bypass a retained receipt.
        if refresh_prior:
            while expected is not None and expected[0] != item["role"]:
                expected = next(evidence_paths, None)
        if expected is None:
            raise ValueError(f"{where}: source evidence role/path mismatch")
        role, template = expected
        if item["role"] != role or item["path"] != template.format(python=python):
            raise ValueError(f"{where}: source evidence role/path mismatch")
        observed = SourceInput(
            role,
            _string(item, "path", where),
            _string(item, "git_object", where),
            _string(item, "text", where),
        )
        if not _GIT_OBJECT_ID.fullmatch(observed.git_object):
            raise ValueError(f"{where}: invalid evidence object id")
        if observed.sha256() != item["sha256"]:
            raise ValueError(f"{where}: source evidence sha256 mismatch")
        if (
            role != "public_headers"
            and _git_blob_id(observed.text.encode("utf-8")) != observed.git_object
        ):
            raise ValueError(f"{where}: source evidence git blob mismatch")
        parsed_inputs.append(observed)
    snapshot = SourceSnapshot(
        python=_string(source, "python", where),
        tag=_string(source, "tag", where),
        revision=_string(source, "revision", where),
        header_object=_string(header, "git_object", f"{where}.header"),
        header_lines=_strings(header, "lines", f"{where}.header"),
        lib_object=_string(lib, "git_object", f"{where}.lib"),
        lib_entries=_strings(lib, "entries", f"{where}.lib"),
        inputs=tuple(parsed_inputs),
    )
    for object_id in (snapshot.revision, snapshot.header_object, snapshot.lib_object):
        if _GIT_OBJECT_ID.fullmatch(object_id) is None:
            raise ValueError(f"{where}: {object_id!r} is not a full git object id")
    if list(snapshot.lib_entries) != sorted(set(snapshot.lib_entries)):
        raise ValueError(f"{where}.lib: entries must be sorted and unique")
    recorded = {
        HEADER_PATH: header["sha256"],
        LIB_PATH: lib["sha256"],
        **{item["path"]: item["sha256"] for item in inputs},
    }
    mismatched = [
        f"{path} (sha256)"
        for path, (_object_id, sha256) in snapshot.receipts().items()
        if sha256 != recorded[path]
    ]
    if _git_blob_id(snapshot.header_bytes()) != snapshot.header_object:
        mismatched.append(f"{HEADER_PATH} (git blob id)")
    if mismatched:
        raise ValueError(
            f"{where}: content does not match its receipt for " + ", ".join(mismatched)
        )
    return snapshot


def load_snapshot(path: Path) -> dict[str, SourceSnapshot]:
    """Every version's complete inputs, each verified against its receipt."""
    return _load_snapshot(path, refresh_prior=False)


def _load_snapshot(path: Path, *, refresh_prior: bool) -> dict[str, SourceSnapshot]:
    try:
        text = canonical_generated_bytes(path.read_bytes()).decode("utf-8")
    except FileNotFoundError:
        raise RuntimeError(
            f"{display_path(path)} is missing; run `{REFRESH_COMMAND}`"
        ) from None
    data = _exact_keys(json.loads(text), {"schema", "sources"}, display_path(path))
    if data["schema"] != SNAPSHOT_SCHEMA:
        raise ValueError(f"{display_path(path)}: schema must be {SNAPSHOT_SCHEMA!r}")
    rows = data["sources"]
    if not isinstance(rows, list):
        raise ValueError(f"{display_path(path)}: sources must be a list")
    snapshots: dict[str, SourceSnapshot] = {}
    for index, row in enumerate(rows):
        snapshot = _snapshot_from_row(
            row, f"{display_path(path)} sources[{index}]", refresh_prior=refresh_prior
        )
        if snapshot.python in snapshots:
            raise ValueError(
                f"{display_path(path)}: duplicate source for {snapshot.python}"
            )
        snapshots[snapshot.python] = snapshot
    if text != render_snapshot(snapshots):
        raise ValueError(
            f"{display_path(path)} is not in canonical form; run `{REFRESH_COMMAND}`"
        )
    return snapshots


def pinned_snapshots(versions: Sequence[str]) -> dict[str, SourceSnapshot]:
    """The snapshot of each version, bound to the pinned source authority."""
    pins = load_cpython_sources(PINS_PATH)
    unpinned = [version for version in versions if version not in pins]
    if unpinned:
        raise RuntimeError(
            f"{display_path(PINS_PATH)} pins no CPython source for {unpinned}"
        )
    snapshots = load_snapshot(SNAPSHOT_PATH)
    problems = [f"{version} is missing" for version in pins if version not in snapshots]
    for version, snapshot in snapshots.items():
        pin = pins.get(version)
        if pin is None:
            problems.append(f"{version} is not a pinned source version")
            continue
        if snapshot is not None and (snapshot.tag, snapshot.revision) != (
            pin.tag,
            pin.revision,
        ):
            problems.append(
                f"{version} holds {snapshot.tag} ({snapshot.revision}) but the pin "
                f"is {pin.tag} ({pin.revision})"
            )
    if problems:
        raise RuntimeError(
            f"{display_path(SNAPSHOT_PATH)} does not match "
            f"{display_path(PINS_PATH)}: {'; '.join(problems)}; "
            f"run `{REFRESH_COMMAND}`"
        )
    return {version: snapshots[version] for version in versions}


