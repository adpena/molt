#!/usr/bin/env python3
"""Generate the typed frontend rejection registry from its TOML authority."""

from __future__ import annotations

import argparse
import ast
from dataclasses import dataclass
import json
from pathlib import Path
import re
import sys
import tempfile
import tomllib


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/molt/frontend/frontend_diagnostics.toml"
OUTPUT = ROOT / "src/molt/frontend/frontend_diagnostics_generated.py"
NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
CODE_RE = re.compile(r"^MOLT-FE([0-9]{3})$")
VALID_TIERS = frozenset({"native", "guarded", "bridge", "unsupported"})
VALID_IMPACTS = frozenset({"low", "medium", "high"})


@dataclass(frozen=True, slots=True)
class Diagnostic:
    name: str
    code: str
    title: str
    tier: str
    impact: str


def load_diagnostics(path: Path = SOURCE) -> tuple[Diagnostic, ...]:
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    if raw.get("schema_version") != 1:
        raise ValueError("frontend diagnostic schema_version must be 1")
    rows = raw.get("diagnostic")
    if not isinstance(rows, list) or not rows:
        raise ValueError("frontend diagnostic authority must define diagnostics")
    diagnostics: list[Diagnostic] = []
    names: set[str] = set()
    codes: set[str] = set()
    for index, row in enumerate(rows, 1):
        if not isinstance(row, dict):
            raise ValueError(f"diagnostic row {index} must be a table")
        diagnostic = Diagnostic(
            name=str(row.get("name", "")),
            code=str(row.get("code", "")),
            title=str(row.get("title", "")),
            tier=str(row.get("tier", "")),
            impact=str(row.get("impact", "")),
        )
        code_match = CODE_RE.fullmatch(diagnostic.code)
        if not NAME_RE.fullmatch(diagnostic.name):
            raise ValueError(f"invalid diagnostic name: {diagnostic.name!r}")
        if code_match is None:
            raise ValueError(f"invalid diagnostic code: {diagnostic.code!r}")
        if not diagnostic.title:
            raise ValueError(f"{diagnostic.name}: title must not be empty")
        if diagnostic.tier not in VALID_TIERS:
            raise ValueError(f"{diagnostic.name}: invalid tier {diagnostic.tier!r}")
        if diagnostic.impact not in VALID_IMPACTS:
            raise ValueError(f"{diagnostic.name}: invalid impact {diagnostic.impact!r}")
        if diagnostic.name in names:
            raise ValueError(f"duplicate diagnostic name: {diagnostic.name}")
        if diagnostic.code in codes:
            raise ValueError(f"duplicate diagnostic code: {diagnostic.code}")
        expected_number = len(diagnostics) + 1
        if int(code_match.group(1)) != expected_number:
            raise ValueError(
                f"{diagnostic.name}: expected MOLT-FE{expected_number:03d}, "
                f"got {diagnostic.code}"
            )
        names.add(diagnostic.name)
        codes.add(diagnostic.code)
        diagnostics.append(diagnostic)
    return tuple(diagnostics)


def render(diagnostics: tuple[Diagnostic, ...]) -> str:
    lines = [
        "# @generated by tools/gen_frontend_diagnostics.py from",
        "# src/molt/frontend/frontend_diagnostics.toml. DO NOT EDIT.",
        "",
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "from typing import Final, Literal, NamedTuple",
        "",
        "",
        "class FrontendDiagnostic(str, Enum):",
    ]
    lines.extend(
        f'    {diagnostic.name.upper()} = "{diagnostic.code}"'
        for diagnostic in diagnostics
    )
    lines.extend(
        [
            "",
            "",
            "class FrontendDiagnosticMetadata(NamedTuple):",
            "    title: str",
            "    detail: str",
            '    tier: Literal["native", "guarded", "bridge", "unsupported"]',
            '    impact: Literal["low", "medium", "high"]',
            "",
            "",
            "FRONTEND_DIAGNOSTIC_METADATA: Final = {",
        ]
    )
    for diagnostic in diagnostics:
        lines.append(
            "    FrontendDiagnostic."
            f"{diagnostic.name.upper()}: FrontendDiagnosticMetadata("
        )
        lines.append(f"        title={json.dumps(diagnostic.title)},")
        lines.append(
            f"        detail={json.dumps(f'{diagnostic.code}: {diagnostic.title}')},"
        )
        lines.append(f"        tier={json.dumps(diagnostic.tier)},")
        lines.append(f"        impact={json.dumps(diagnostic.impact)},")
        lines.append("    ),")
    lines.extend(["}", ""])
    return "\n".join(lines)


def _is_name(node: ast.AST | None, name: str) -> bool:
    return isinstance(node, ast.Name) and node.id == name


def validate_consumers(
    diagnostics: tuple[Diagnostic, ...], root: Path = ROOT
) -> tuple[int, dict[str, int]]:
    """Reject legacy stub lanes and untyped frontend rejection construction."""

    known = {diagnostic.name.upper() for diagnostic in diagnostics}
    used = {name: 0 for name in known}
    violations: list[str] = []
    total = 0
    frontend_root = root / "src/molt/frontend"
    for path in sorted(frontend_root.rglob("*.py")):
        if path.name == OUTPUT.name or path.name == "diagnostics.py":
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        relative = path.relative_to(root).as_posix()
        for node in ast.walk(tree):
            if isinstance(node, ast.Raise) and isinstance(node.exc, ast.Call):
                if _is_name(node.exc.func, "NotImplementedError"):
                    violations.append(
                        f"{relative}:{node.lineno}: direct NotImplementedError "
                        "raise bypasses the frontend diagnostic authority"
                    )
            if not isinstance(node, ast.Call):
                continue
            if (
                isinstance(node.func, ast.Attribute)
                and node.func.attr == "unsupported"
                and isinstance(node.func.value, ast.Attribute)
                and node.func.value.attr == "compat"
            ):
                violations.append(
                    f"{relative}:{node.lineno}: direct compat.unsupported call "
                    "bypasses the frontend diagnostic authority"
                )
            if not _is_name(node.func, "FrontendRejection"):
                continue
            total += 1
            first = node.args[0] if node.args else None
            if not (
                isinstance(first, ast.Attribute)
                and (
                    _is_name(first.value, "FrontendDiagnostic")
                    or _is_name(first.value, "Diagnostic")
                )
                and first.attr in known
            ):
                violations.append(
                    f"{relative}:{node.lineno}: FrontendRejection requires a "
                    "generated FrontendDiagnostic member"
                )
                continue
            if not 2 <= len(node.args) <= 4 or node.keywords:
                violations.append(
                    f"{relative}:{node.lineno}: FrontendRejection requires 2-4 "
                    "positional authority fields"
                )
            used[first.attr] += 1
    emission_core = frontend_root / "lowering/emission_core.py"
    emission_tree = ast.parse(
        emission_core.read_text(encoding="utf-8"), filename=str(emission_core)
    )
    for node in ast.walk(emission_tree):
        if not isinstance(node, ast.ExceptHandler):
            continue
        caught = node.type
        names: list[ast.AST] = (
            list(caught.elts) if isinstance(caught, ast.Tuple) else [caught]
        )
        if any(_is_name(name, "NotImplementedError") for name in names):
            violations.append(
                "src/molt/frontend/lowering/emission_core.py:"
                f"{node.lineno}: legacy NotImplementedError conversion lane"
            )
    unused = sorted(name for name, count in used.items() if count == 0)
    if unused:
        violations.append(f"unused frontend diagnostics: {', '.join(unused)}")
    if violations:
        raise ValueError(
            "frontend diagnostic consumer violations:\n" + "\n".join(violations)
        )
    return total, dict(sorted(used.items()))


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", newline="\n", dir=path.parent, delete=False
    ) as handle:
        handle.write(text)
        temporary = Path(handle.name)
    temporary.replace(path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    diagnostics = load_diagnostics()
    validate_consumers(diagnostics)
    expected = render(diagnostics)
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print(f"stale generated frontend diagnostics: {OUTPUT}", file=sys.stderr)
            return 1
        return 0
    _write_atomic(OUTPUT, expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
