from __future__ import annotations

import textwrap
from pathlib import Path

import pytest

import tools.pact_witness_numpy_generated_modules as gen


# A stand-in for NumPy's own numpy/_build_utils/gitversion.py: it reads the
# version from pyproject.toml and writes a version.py in NumPy's real shape.
# This exercises the tool's contract -- run the checkout's authoritative
# generator, then verify the emitted module carries the pyproject version --
# without depending on a provisioned NumPy checkout.
_FAKE_GITVERSION = textwrap.dedent(
    '''
    import argparse
    import os
    import textwrap


    def init_version():
        here = os.path.dirname(__file__)
        pyproject = os.path.join(here, "..", "..", "pyproject.toml")
        with open(pyproject) as fid:
            for line in fid:
                if line.startswith("version ="):
                    return line.split("=", 1)[1].strip().strip("\\"'")
        raise SystemExit("no version in pyproject.toml")


    if __name__ == "__main__":
        parser = argparse.ArgumentParser()
        parser.add_argument("--write")
        args = parser.parse_args()
        version = init_version()
        template = textwrap.dedent(f\'\'\'
            """
            Module to expose more detailed version info for the installed `numpy`
            """
            version = "{version}"
            __version__ = version
            full_version = version

            git_revision = "deadbeef"
            release = 'dev' not in version and '+' not in version
            short_version = version.split("+")[0]
        \'\'\')
        with open(args.write, "w") as fid:
            fid.write(template)
    '''
)

_FAKE_CONFIG = textwrap.dedent(
    '''
    # This file is generated by numpy's build process
    from numpy._core._multiarray_umath import (
        __cpu_features__,
        __cpu_baseline__,
        __cpu_dispatch__,
    )

    __all__ = ["show_config"]
    _built_with_meson = True


    def show_config(mode="stdout"):
        return None
    '''
)


def _make_repo(tmp_path: Path, *, version: str = "7.7.7") -> Path:
    repo = tmp_path / "repo"
    # NumPy source checkout with pyproject + gitversion generator.
    numpy_src = repo / gen._NUMPY_SOURCE_REL
    (numpy_src / "numpy" / "_build_utils").mkdir(parents=True)
    (numpy_src / "pyproject.toml").write_text(
        f'[project]\nversion = "{version}"\n', encoding="utf-8"
    )
    (numpy_src / "numpy" / "_build_utils" / "gitversion.py").write_text(
        _FAKE_GITVERSION, encoding="utf-8"
    )
    (numpy_src / "numpy" / "__init__.py").write_text("V = 1\n", encoding="utf-8")
    # Real meson build output carrying __config__.py.
    build_cfg = (
        repo
        / "tmp/pact_numpy_multiarray_meson_wasm_build_generated/numpy/__config__.py"
    )
    build_cfg.parent.mkdir(parents=True)
    build_cfg.write_text(_FAKE_CONFIG, encoding="utf-8")
    # Witness sealed numpy package root.
    seal_numpy = repo / "tmp/pact_numpy_multiarray_sealed_for_witness/numpy"
    seal_numpy.mkdir(parents=True)
    (seal_numpy / "__init__.py").write_text("V = 1\n", encoding="utf-8")
    return repo


def test_materialize_writes_generated_modules_into_every_witness_root(
    tmp_path: Path,
) -> None:
    repo = _make_repo(tmp_path, version="7.7.7")

    written = gen.materialize(repo)

    seal_numpy = repo / "tmp/pact_numpy_multiarray_sealed_for_witness/numpy"
    ots_numpy = repo / gen._NUMPY_SOURCE_REL / "numpy"
    for numpy_dir in (seal_numpy, ots_numpy):
        version_py = numpy_dir / "version.py"
        config_py = numpy_dir / "__config__.py"
        assert version_py.is_file(), version_py
        assert config_py.is_file(), config_py
        text = version_py.read_text(encoding="utf-8")
        assert 'version = "7.7.7"' in text
        assert "__version__ = version" in text
        assert 'show_config' in config_py.read_text(encoding="utf-8")
    # Both files, both roots.
    assert len(written) == 4


def test_version_string_is_sourced_from_pyproject_not_a_literal(
    tmp_path: Path,
) -> None:
    repo = _make_repo(tmp_path, version="3.2.1")
    gen.materialize(repo)
    seal_version = (
        repo
        / "tmp/pact_numpy_multiarray_sealed_for_witness/numpy/version.py"
    )
    assert 'version = "3.2.1"' in seal_version.read_text(encoding="utf-8")


def test_check_flags_missing_then_passes_after_materialize(tmp_path: Path) -> None:
    repo = _make_repo(tmp_path)
    problems = gen.check(repo)
    assert problems and any("missing generated module" in p for p in problems)

    gen.materialize(repo)
    assert gen.check(repo) == []


def test_missing_config_build_output_fails_closed(tmp_path: Path) -> None:
    repo = _make_repo(tmp_path)
    # Remove the authoritative meson build output; the tool must refuse to
    # fabricate build metadata.
    (
        repo
        / "tmp/pact_numpy_multiarray_meson_wasm_build_generated/numpy/__config__.py"
    ).unlink()
    with pytest.raises(gen.GeneratedModuleError) as excinfo:
        gen.materialize(repo)
    assert "__config__.py" in str(excinfo.value)


def test_version_module_version_mismatch_fails_closed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = _make_repo(tmp_path, version="1.0.0")
    numpy_src = repo / gen._NUMPY_SOURCE_REL

    # gitversion emits a version that disagrees with pyproject -> fail closed.
    def _bad_version(root: Path) -> str:
        _ = root
        return "9.9.9"

    monkeypatch.setattr(gen, "_numpy_pyproject_version", _bad_version)
    with pytest.raises(gen.GeneratedModuleError) as excinfo:
        gen._generate_version_module(numpy_src)
    assert "9.9.9" in str(excinfo.value)
