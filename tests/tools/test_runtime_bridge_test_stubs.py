from __future__ import annotations

from pathlib import Path
from types import ModuleType

from tools import check_runtime_bridge_test_stubs


def _write_fixture(root: Path, *, stub_body: str = "") -> Path:
    core = root / "runtime" / "molt-runtime-core" / "src"
    core.mkdir(parents=True)
    (core / "lib.rs").write_text(
        """
unsafe extern "C" {
    pub fn molt_core_symbol(value: u64) -> u64;
}
""",
        encoding="utf-8",
    )

    satellite = root / "runtime" / "molt-runtime-compression" / "src"
    satellite.mkdir(parents=True)
    (satellite / "bridge.rs").write_text(
        """
extern "C" {
    pub fn molt_bridge_plain(value: i64) -> u64;
}

unsafe extern "C" {
    fn molt_bridge_unsafe(ptr: *mut u8);
}
""",
        encoding="utf-8",
    )

    native = root / "runtime/molt-runtime-capi/src"
    native.mkdir(parents=True)
    (native / "lib.rs").write_text(
        'unsafe extern "C" {\n    fn molt_native_retirement();\n}\n',
        encoding="utf-8",
    )
    gpu = root / "runtime/molt-gpu-runtime/src"
    gpu.mkdir(parents=True)
    (gpu / "bridge.rs").write_text("", encoding="utf-8")

    stub = core / "bridge_test_stubs.rs"
    stub.write_text(stub_body, encoding="utf-8")
    return stub


def _point_tool_at(tool: ModuleType, monkeypatch, root: Path, stub: Path) -> None:
    monkeypatch.setattr(tool, "REPO_ROOT", root)
    monkeypatch.setattr(tool, "STUB_PATH", stub)


def test_parser_covers_core_plain_and_unsafe_externs(monkeypatch, tmp_path):
    tool = check_runtime_bridge_test_stubs
    stub = _write_fixture(tmp_path)
    _point_tool_at(tool, monkeypatch, tmp_path, stub)

    assert tool.declared_bridge_symbols() == [
        "molt_bridge_plain",
        "molt_bridge_unsafe",
        "molt_core_symbol",
        "molt_native_retirement",
    ]


def test_write_publishes_canonical_stub(monkeypatch, tmp_path):
    tool = check_runtime_bridge_test_stubs
    stub = _write_fixture(tmp_path)
    _point_tool_at(tool, monkeypatch, tmp_path, stub)

    assert tool.main(["--check"]) == 1
    assert tool.main(["--write"]) == 0
    body = stub.read_text(encoding="utf-8")
    assert "aborting_bridge_stub!(molt_bridge_plain);" in body
    assert "aborting_bridge_stub!(molt_bridge_unsafe);" in body
    assert "aborting_bridge_stub!(molt_core_symbol);" in body
    assert "aborting_bridge_stub!(molt_native_retirement);" in body
    assert (
        "// @generated by tools/check_runtime_bridge_test_stubs.py --write. DO NOT EDIT."
        in body
    )
    assert tool.main(["--check"]) == 0


def test_missing_stub_fails_closed(monkeypatch, tmp_path, capsys):
    tool = check_runtime_bridge_test_stubs
    stub = _write_fixture(
        tmp_path,
        stub_body="aborting_bridge_stub!(molt_core_symbol);\n",
    )
    _point_tool_at(tool, monkeypatch, tmp_path, stub)

    assert tool.main(["--check"]) == 1
    assert f"stale: {stub}" in capsys.readouterr().err
    # The stale check never repairs: the incomplete stub file is left untouched.
    assert (
        stub.read_text(encoding="utf-8") == "aborting_bridge_stub!(molt_core_symbol);\n"
    )


def test_live_stub_file_is_in_sync():
    tool = check_runtime_bridge_test_stubs

    assert tool.main(["--check"]) == 0
    symbols = tool.declared_bridge_symbols()
    from molt._wasm_abi_generated import runtime_execution_abi

    for logical in ("molt_bytes_from", "__molt_runtime_release_protected_value"):
        execution = runtime_execution_abi(logical)
        assert execution is not None
        assert execution.physical_symbol in symbols


def test_bridge_stubs_use_actual_link_identities(tmp_path, monkeypatch) -> None:
    from molt._wasm_abi_generated import runtime_execution_abi

    source = tmp_path / "bridge.rs"
    source.write_text(
        """unsafe extern "C" {
    #[link_name = molt_runtime_core::attached_symbol!("molt_add")]
    fn local_add(context: u64, a: u64, b: u64) -> u64;
    #[link_name = "raw_link"]
    fn local_raw() -> u64;
    fn unchanged_raw() -> u64;
}
""",
        encoding="utf-8",
    )
    monkeypatch.setattr(
        check_runtime_bridge_test_stubs, "bridge_sources", lambda: [source]
    )
    execution = runtime_execution_abi("molt_add")
    assert execution is not None
    assert check_runtime_bridge_test_stubs.declared_bridge_symbols() == sorted(
        [
            execution.physical_symbol,
            "raw_link",
            "unchanged_raw",
        ]
    )
