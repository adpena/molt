PLAN = proof_plan.ProofPlan.load()


def _plan_gate_toolchains(gate: str) -> set[str]:
    """The toolchain closure of every plan rule or landing gate that runs ``gate``."""
    closures = [
        set(PLAN.toolchain_closure(rule["toolchains"]))
        for rule in PLAN.local_rules
        if gate in rule.get("gates", ())
    ]
    if gate in PLAN.always:
        closures.append(set(PLAN.toolchain_closure(PLAN.always_toolchains)))
    assert closures, f"no proof-plan gate runs {gate!r}"
    return set().union(*closures)


def test_generated_rust_is_classified_by_header(tmp_path) -> None:
    tool = check_rustfmt
    generated = tmp_path / "table.rs"
    generated.write_text(
        "//! @generated by tools/gen_codecs.py from source.\n//! DO NOT EDIT.\n",
        encoding="utf-8",
    )
    human = tmp_path / "lib.rs"
    human.write_text("fn main() {}\n", encoding="utf-8")

    assert tool.is_generated_rust(generated) is True
    assert tool.is_generated_rust(human) is False
    assert tool.generated_owner(generated) == "python tools/gen_codecs.py --check"


def test_third_party_rust_is_skipped_by_default(tmp_path, monkeypatch) -> None:
    tool = check_rustfmt
    monkeypatch.setattr(tool, "ROOT", tmp_path)
    source = tmp_path / "vendor" / "crate" / "src" / "lib.rs"
    source.parent.mkdir(parents=True)
    source.write_text("pub fn vendored() {}\n", encoding="utf-8")

    selection = tool.select_rust_paths((Path("vendor/crate/src/lib.rs"),))

    assert selection.human == ()
    assert selection.generated == ()
    assert selection.third_party == (Path("vendor/crate/src/lib.rs"),)


def test_rustfmt_command_chunking_keeps_windows_command_lines_bounded() -> None:
    tool = check_rustfmt
    paths = tuple(Path(f"runtime/crate/src/{idx:04d}_module.rs") for idx in range(800))

    commands = tool._chunked_rustfmt_commands(
        "rustfmt",
        paths,
        check=True,
        edition="2024",
    )

    assert len(commands) > 1
    assert all(
        command[:6]
        == [
            "rustfmt",
            "--edition",
            "2024",
            "--config",
            "skip_children=true",
            "--check",
        ]
        for command in commands
    )
    assert all(
        sum(len(part) + 1 for part in command) <= tool.WINDOWS_COMMAND_LINE_SOFT_LIMIT
        for command in commands
    )


def test_explicit_rust_paths_expand_files_and_directories(
    monkeypatch, tmp_path
) -> None:
    tool = check_rustfmt
    monkeypatch.setattr(tool, "ROOT", tmp_path)
    src = tmp_path / "runtime" / "crate" / "src"
    src.mkdir(parents=True)
    (src / "lib.rs").write_text("pub fn lib() {}\n", encoding="utf-8")
    (src / "README.md").write_text("not rust\n", encoding="utf-8")
    single = tmp_path / "tools" / "one.rs"
    single.parent.mkdir()
    single.write_text("fn one() {}\n", encoding="utf-8")

    paths = tool._explicit_rust_paths(["runtime/crate/src", "tools/one.rs"])

    assert paths == (
        Path("runtime/crate/src/lib.rs"),
        Path("tools/one.rs"),
    )


def test_write_mode_preserves_noop_crlf_bytes(monkeypatch, tmp_path) -> None:
    tool = check_rustfmt
    monkeypatch.setattr(tool, "ROOT", tmp_path)
    source = tmp_path / "src" / "main.rs"
    source.parent.mkdir()
    source.write_bytes(b'fn main() {\r\n    println!("ok");\r\n}\r\n')

    monkeypatch.setattr(
        tool,
        "_rustfmt_stdout",
        lambda _path, _edition: b'fn main() {\n    println!("ok");\n}\n',
    )

    assert tool._run_rustfmt((Path("src/main.rs"),), check=False, edition="2024") == 0
    assert source.read_bytes() == b'fn main() {\r\n    println!("ok");\r\n}\r\n'


def test_rustfmt_stdout_selects_requested_windows_section(
    monkeypatch, tmp_path
) -> None:
    tool = check_rustfmt
    monkeypatch.setattr(tool, "ROOT", tmp_path)
    source = tmp_path / "src" / "lib.rs"
    child = tmp_path / "src" / "child.rs"
    source.parent.mkdir()
    payload = (
        f"\\\\?\\{source}:\n\n".encode("utf-8")
        + b"mod child;\n"
        + f"\n\\\\?\\{child}:\n\n".encode("utf-8")
        + b"pub fn child() {}\n"
    )

    assert (
        tool._select_rustfmt_stdout_section(payload, Path("src/lib.rs"))
        == b"mod child;\n"
    )


